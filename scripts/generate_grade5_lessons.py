VALID_DIFFICULTY = {"direct", "near_transfer", "stretch", "challenge"}


def validate(t):
    """Light self-check so a bad topic never ships silently."""
    assert t["id"] and t["topic"] and t["emoji"], "topic meta missing"
    assert len(t["gradeRange"]) == 2, "gradeRange must be [min,max]"
    assert len(t["levels"]) == 5, f"{t['id']}: expected 5 levels"
    seen_ids = set()
    for lv in t["levels"]:
        assert len(lv["lessons"]) == 5, f"{t['id']} L{lv['id']}: need 5 lessons"
        assert len(lv["quiz"]) == 8, f"{t['id']} L{lv['id']}: need 8 quiz"
        for q in lv["quiz"]:
            assert q["id"] not in seen_ids, f"dup quiz id {q['id']}"
            seen_ids.add(q["id"])
            assert q["difficulty"] in VALID_DIFFICULTY, f"bad difficulty {q['difficulty']}"
            ans = q["answer"]
            assert isinstance(ans, str) and ans != "", f"empty answer {q['id']}"
            # Plain-arithmetic answers must stay free of LaTeX control chars so the
            # exact-match grader compares clean strings.
            assert "\\" not in ans and "{" not in ans, f"answer has latex {q['id']}: {ans}"


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    written = []
    for build in BUILDERS:
        t = build()
        validate(t)
        path = os.path.join(OUT_DIR, f"{t['id']}.json")
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(t, fh, ensure_ascii=False, indent=2)
        written.append(t["id"])
        print(f"  wrote {t['id']}.json  ({len(t['levels'])} levels)")
    print(f"\nDone: {len(written)} topic files written to {OUT_DIR}")


if __name__ == "__main__":
    main()
