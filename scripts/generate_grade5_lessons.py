# ── Answer-format helpers (canonical strings for the exact-match grader) ───────
def dstr(x):
    """Decimal -> canonical string, trailing zeros stripped. 0.80 -> '0.8'."""
    s = f"{x:.6f}".rstrip("0").rstrip(".")
    if s == "-0":
        s = "0"
    return s


def frac(a, b):
    """Fraction in lowest terms -> 'n/d' (or whole number if d==1)."""
    f = Fraction(a, b)
    if f.denominator == 1:
        return str(f.numerator)
    return f"{f.numerator}/{f.denominator}"


def round_half_up(n, base):
    """Round n to nearest multiple of base, .5 always rounds UP (as taught)."""
    return int(math.floor(n / base + 0.5)) * base


# ── Builders ──────────────────────────────────────────────────────────────────
def L(lid, title, intro, explanation, rule, tip, visual="", steps=None):
    d = {
        "id": lid,
        "title": title,
        "intro": intro,
        "visual": visual,
        "explanation": explanation,
        "rule": rule,
        "tip": tip,
    }
    if steps:
        d["steps"] = steps
    return d


def Q(qid, question, answer, hint, difficulty, story=None, isWord=None):
    d = {"id": qid, "question": question, "answer": str(answer), "hint": hint,
         "difficulty": difficulty}
    if story is not None:
        d["story"] = story
    if isWord is not None:
        d["isWord"] = isWord
    return d


def level(level_id, label, subtitle, lessons, quiz):
    emoji, color, grad = LEVEL_STYLE[level_id - 1]
    return {
        "id": level_id,
        "label": label,
        "emoji": emoji,
        "color": color,
        "bgGradient": grad,
        "subtitle": subtitle,
        "lessons": lessons,
        "quiz": quiz,
    }


def topic(slug, name, emoji, color, grade_range, description, levels):
    return {
        "id": slug,
        "topic": name,
        "emoji": emoji,
        "color": color,
        "gradeRange": grade_range,
        "description": description,
        "levels": levels,
    }


# A compact 5-lesson pack builder so each level has 5 genuine lessons without
# hand-repeating boilerplate. `specs` is a list of 5 (title, intro, expl, rule, tip)
# tuples; the first may carry optional steps.
def lessons5(prefix, specs):
    out = []
    for i, s in enumerate(specs, start=1):
        title, intro, expl, rule, tip = s[0], s[1], s[2], s[3], s[4]
        steps = s[5] if len(s) > 5 else None
        out.append(L(f"{prefix}-les{i}", title, intro, expl, rule, tip, steps=steps))
    return out


