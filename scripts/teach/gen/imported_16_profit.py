# Kavya's mother: 3 bundles at 160, 120, 80; 40 bags at 25.
LESSONS[P + "d5003ab3-2083-4a00-bd93-2f99d861cf8b"] = LESSON(
    B("Kavya's mother buys 3 bundles of paper at 160 rupees each, glue and stickers for 120 rupees, and pays 80 rupees stall rent. She sells 40 bags at 25 rupees each. What is her profit?",
      GIVEN("q", "Costs: 3 × ₹160, ₹120, ₹80.   Sells 40 × ₹25")),
    B("Profit is the money that came in, take away all the money that went out. So we need two totals.",
      LB("r", RULE)),
    B("Start with the paper. How much did the paper cost her?",
      ask=CHOOSE(["160 rupees", "480 rupees", "320 rupees"], 1,
                 "160 rupees is the price of one bundle, and she buys 3 of them. So the paper costs 3 times 160.")),
    B("3 times 160 is 480. So the paper costs 480 rupees.",
      W("l1", "3 × 160 = 480")),
    B("Now add up everything she spent: 480 for paper, 120 for glue and stickers, and 80 for rent. That makes 680 rupees.",
      W("l2", "480 + 120 + 80 = 680"), NOTE("l2", "680", "money out")),
    B("Next, the money that came in. 40 bags at 25 rupees each is 40 times 25, which is 1000 rupees.",
      W("l3", "40 × 25 = 1000"), NOTE("l3", "1000", "money in")),
    B("Now take the money out away from the money in. 1000 minus 680 is 320. Her profit is 320 rupees.",
      *ANSC("l4", "1000 − 680 = 320", 320)),
    B("The trap is leaving out a cost. Take off only the paper and you get 520, which is one of the choices. The glue and the rent are costs too.",
      W("l5", "1000 − 480 = 520"), NOTE("l5", "520", "leaves out costs")),
    B("Check by adding back. Her costs of 680, plus her profit of 320, should make the 1000 she took in. And they do.",
      W("l6", "680 + 320 = 1000")),
    B("So for profit: add up every cost, work out everything earned, then take the costs away from the earnings."),
)

