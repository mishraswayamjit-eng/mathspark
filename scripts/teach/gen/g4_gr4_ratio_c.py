    beat("Now 4 more red marbles go in. Where do we add the 4?",
         ask=ask(["to the 2 in the ratio", "to the 8 red marbles", "to both colours"], 1,
                 "The 4 are real marbles, so they join the real red marbles, the 8. The 2 in the ratio is a number of parts, not marbles.")),
    beat("8 plus 4 is 12 red marbles. The green ones have not changed: still 12.", W("w5", "8 + 4 = 12")),
    beat("So the new ratio is 12 to 12. Divide both by 12 and we get 1 to 1.", Lb("w6", "12 : 12"), W("w7", "12 ÷ 12 = 1")),
