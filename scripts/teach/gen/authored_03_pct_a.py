"""Percentage lessons for part 03, written one by one (first half)."""
from authored_03_lib import ANSC, ANSL, B, CHOOSE, CIRC, GIVEN, LB, LESSON, NOTE, P, UL, W  # noqa: F401

LESSONS = {}

# Up 20%, then the new price down 20%.
LESSONS[P + "PERCENTAGE_001"] = LESSON(
    B("The price of a cricket bat is raised by 20 percent. A month later, the new price is cut by 20 percent. How does the final price compare with the price at the very beginning?",
      GIVEN("q", "Price raised by 20%. Then the new price is cut by 20%."), GIVEN("q2", "Final price compared with the start?")),
    B("Up 20 percent, then down 20 percent. Before we work it out, what do you expect?",
      ask=CHOOSE(["back where it started", "lower than the start", "higher than the start"], 1,
                 "It feels as if the two changes cancel. But they are 20 percent of two different prices. Let's follow a real price through and see.")),
    B("No price is given, so we can choose an easy one. Say the bat costs 100 rupees at the beginning.",
      LB("l1", "Start: ₹100")),
    B("First the rise. 20 percent of 100 is 20, so the price goes up to 120 rupees.",
      W("l2", "20% of 100 = 20"), W("l3", "100 + 20 = 120")),
    B("Now the 20 percent cut. It is 20 percent of which price?",
      ask=CHOOSE(["of 100, the first price", "of 120, the new price", "of 20, the rise"], 1,
                 "Read the question again: it is the new price that is cut. The cut is taken from what the bat costs at that moment, which is 120.")),
    B("20 percent of 120 is 24. That is the heart of it: the cut is taken from a bigger price, so it is bigger than the rise was.",
      UL("q", "new price"), W("l4", "20% of 120 = 24")),
    B("120 minus 24 is 96. The final price is 96 rupees.",
      W("l5", "120 − 24 = 96")),
    B("96 is 4 rupees below 100, and 4 out of 100 is 4 percent. So the final price is 4 percent less than at the beginning.",
      W("l6", "100 − 96 = 4"), *ANSL("l7", "Final price: 4% less than at the start", "4% less")),
    B("So the same percent up and then down does not bring you back. Each percent belongs to the price just before it, and starting from 100 makes that easy to follow."),
)

# Raised 20%, then reduced 10%, now Rs 594.
LESSONS[P + "PERCENTAGE_002"] = LESSON(
    B("A bus fare was raised by 20 percent. Later the new fare was reduced by 10 percent, and it is now 594 rupees. What was the fare before the two changes?",
      GIVEN("q", "Fare raised by 20%, then reduced by 10%. Now ₹594."), GIVEN("q2", "Fare before the changes?")),
    B("We know the end and want the beginning. So we work backwards, undoing the last change first."),
    B("The last change was the 10 percent cut. After a 10 percent cut, 90 percent of the raised fare is left.",
      W("l1", "100% − 10% = 90%")),
    B("So 594 rupees is 90 percent of the raised fare. Divide by 9 to find 10 percent: 594 divided by 9 is 66.",
      W("l2", "594 ÷ 9 = 66"), NOTE("l2", "66", "10% of raised fare")),
    B("10 percent is 66, so the whole raised fare is 10 times that: 660 rupees.",
      W("l3", "66 × 10 = 660")),
    B("Now undo the 20 percent rise. 660 is what percent of the first fare?",
      ask=CHOOSE(["80%", "120%", "20%"], 1,
                 "The first fare is the whole, 100 percent. Raising it by 20 percent puts 20 more on top, so the raised fare is 120 percent of the first fare.")),
    B("660 is 120 percent of the first fare. Divide by 12 to find 10 percent: 660 divided by 12 is 55.",
      W("l4", "100% + 20% = 120%"), W("l5", "660 ÷ 12 = 55")),
    B("10 percent is 55, so the first fare is 10 times that. It was 550 rupees.",
      *ANSC("l6", "55 × 10 = 550", 550)),
    B("The tempting move is to say: up 20, down 10, so up 10 overall. But the two percents belong to different fares, so they cannot be mixed."),
    B("Check forwards. 20 percent of 550 is 110, making 660. 10 percent of 660 is 66, and 660 minus 66 is 594. It fits.",
      W("l7", "550 + 110 = 660"), W("l8", "660 − 66 = 594")),
    B("So to undo percent changes: go backwards one change at a time, and ask each time what percent of the earlier amount you are holding."),
)

# Anil is 25% more than Binu: Binu is what percent less than Anil?
LESSONS[P + "PERCENTAGE_003"] = LESSON(
    B("Anil's weight is 25 percent more than Binu's weight. By what percent is Binu's weight less than Anil's?",
      GIVEN("q", "Anil's weight is 25% more than Binu's."), GIVEN("q2", "Binu's is what percent less than Anil's?")),
    B("No weights are given, so we can choose an easy one. Say Binu weighs 100 units.",
      LB("l1", "Binu: 100 units")),
    B("Anil weighs 25 percent more. 25 percent of 100 is 25, so Anil weighs 125 units.",
      W("l2", "100 + 25 = 125"), NOTE("l2", "125", "Anil")),
    B("The gap between them is 25 units, whichever way you look at it.",
      W("l3", "125 − 100 = 25")),
    B("Now the question: Binu is what percent less than Anil? Which weight do we compare the 25 with?",
      ask=CHOOSE(["Binu's 100", "Anil's 125", "either, it is the same"], 1,
                 "Listen to the words: less than Anil's weight. The weight named after the word than is the one we measure against. That is Anil's 125.")),
    B("So we want 25 out of 125. 125 divided by 25 is 5, so 25 is one fifth of 125.",
      UL("q2", "less than Anil's"), W("l4", "125 ÷ 25 = 5")),
    B("One fifth, as a percent, is 20 percent. So Binu's weight is 20 percent less than Anil's.",
      *ANSC("l5", "25/125 = 20%", "20%")),
    B("See the trap? 25 percent more one way is not 25 percent less the other way. The gap is the same 25 units, but it is measured against a bigger weight, so the percent is smaller."),
    B("Check: 20 percent of 125 is 25, and 125 minus 25 is 100. That is Binu's weight.",
      W("l6", "20% of 125 = 25")),
    B("So with percent more or less, always ask: than whom? That person's amount is the base you measure against."),
)

# Farida Rs 400, Gopal Rs 500: which statement is true?
LESSONS[P + "PERCENTAGE_004"] = LESSON(
    B("Farida has 400 rupees and Gopal has 500 rupees. One of the four statements about them is true. Let's find out which.",
      GIVEN("q", "Farida: ₹400. Gopal: ₹500. Which statement is true?")),
    B("Every statement talks about more or less, so start with the difference. 500 minus 400 is 100 rupees.",
      W("l1", "500 − 400 = 100")),
    B("Here is the key idea. That 100 rupees is a different percent, depending on whose money we measure it against."),
    B("Take the words: Gopal has more than Farida. Whose money do we measure the 100 against?",
      ask=CHOOSE(["Farida's 400", "Gopal's 500"], 0,
                 "The person named after the word than is the base. More than Farida means we compare the gap with Farida's 400.")),
    B("100 out of 400 is one quarter, and one quarter is 25 percent. So Gopal has 25 percent more than Farida.",
      W("l2", "100/400 = 25%")),
    B("Now the other way. Farida has less than Gopal, so we measure against Gopal's 500. 100 out of 500 is one fifth, which is 20 percent.",
      W("l3", "100/500 = 20%")),
    B("So Farida has 20 percent less than Gopal, not 25. And Gopal has 25 percent more than Farida, not 20. Two statements swap these numbers round, and that is the trap."),
    B("What about 80 percent less? 400 is 80 percent of 500. That is how much Farida has, not how much less she has.",
      W("l4", "400/500 = 80%")),
    B("So the true statement is: Gopal has 25 percent more money than Farida.",
      *ANSL("l5", "Gopal has 25% more money than Farida.", "25% more")),
    B("With percent more or less, always ask: than whom? The same gap of 100 rupees is 25 percent of one amount and 20 percent of the other."),
)

# 40% on a bag, 25% of the rest on a bottle, Rs 315 left.
LESSONS[P + "PERCENTAGE_005"] = LESSON(
    B("Meera spent 40 percent of her money on a school bag. Then she spent 25 percent of the money that was left on a water bottle. She now has 315 rupees. How much did she have at first?",
      GIVEN("q", "40% on a bag, then 25% of what was left. Now ₹315.")),
    B("The second percent is of what was left, not of all her money. That is the trap. So we work backwards from the 315 rupees.",
      UL("q", "of what was left")),
    B("She spent 25 percent of the money left after the bag. What percent of that money still remains?",
      ask=CHOOSE(["25%", "75%", "35%"], 1,
                 "25 percent is one quarter. Spending one quarter of something leaves three quarters of it, and three quarters is 75 percent.")),
    B("So 315 rupees is three quarters of the money she had after the bag. One quarter is 315 divided by 3, which is 105.",
      W("l1", "315 ÷ 3 = 105"), NOTE("l1", "105", "one quarter")),
    B("4 quarters make the whole: 105 times 4 is 420. She had 420 rupees after buying the bag.",
      W("l2", "105 × 4 = 420"), NOTE("l2", "420", "after the bag")),
    B("The bag took 40 percent of all her money. So 420 rupees is what percent of the starting amount?",
      ask=CHOOSE(["40%", "60%", "35%"], 1,
                 "The 40 percent is the part she spent. The 420 rupees is the part she kept. The two parts make the whole, so she kept 60 percent.")),
    B("420 is 60 percent of the start. Divide by 6 to find 10 percent: 420 divided by 6 is 70.",
      W("l3", "100% − 40% = 60%"), W("l4", "420 ÷ 6 = 70")),
    B("10 percent is 70, so the whole amount is 10 times that. Meera had 700 rupees at first.",
      *ANSC("l5", "70 × 10 = 700", 700)),
    B("The tempting slip is to add 40 and 25, and say 35 percent is left. But the 25 percent was taken from a smaller amount, not from all her money."),
    B("Check forwards. 40 percent of 700 is 280, leaving 420. 25 percent of 420 is 105, leaving 315. It fits.",
      W("l6", "700 − 280 = 420"), W("l7", "420 − 105 = 315")),
    B("So when a percent is taken of what was left: work backwards, one spend at a time, from the money you have at the end."),
)

# Asha 30%, 15 short. Bala 45%, 30 over. Total marks?
LESSONS[P + "PERCENTAGE_006"] = LESSON(
    B("Asha scored 30 percent of the total marks and was 15 marks short of the pass mark. Bala scored 45 percent of the total and got 30 marks more than the pass mark. What were the total marks?",
      GIVEN("q", "Asha: 30% of the total, 15 below the pass mark."), GIVEN("q2", "Bala: 45% of the total, 30 above the pass mark.")),
    B("We do not know the pass mark or the total. But both children are measured against the same pass mark, so let's compare them with each other."),
    B("Asha is 15 marks below the pass mark and Bala is 30 marks above it. How many marks apart are they?",
      ask=CHOOSE(["30 − 15 = 15 marks", "15 + 30 = 45 marks", "30 marks"], 1,
                 "Picture a ladder. Asha stands 15 steps below the pass mark and Bala stands 30 steps above it. To climb from Asha to Bala you go up 15, and then 30 more.")),
    B("15 plus 30 is 45. Bala has 45 marks more than Asha.",
      W("l1", "15 + 30 = 45"), NOTE("l1", "45", "marks apart")),
    B("Now the same gap in percent. Bala has 45 percent and Asha has 30 percent, so the gap is 15 percent of the total.",
      W("l2", "45% − 30% = 15%")),
    B("So 15 percent of the total is 45 marks. That is the link that unlocks the question.",
      LB("l3", "15% of the total = 45 marks")),
    B("If 15 percent is 45 marks, how do we find 1 percent?",
      ask=CHOOSE(["45 ÷ 15", "45 × 15", "45 − 15"], 0,
                 "15 equal pieces make 45 marks. To find one piece, share 45 by 15.")),
    B("45 divided by 15 is 3, so 1 percent is 3 marks. The whole test is 100 percent, which is 3 times 100. The total is 300 marks.",
      W("l4", "45 ÷ 15 = 3"), *ANSC("l5", "3 × 100 = 300", 300)),
    B("Check. Asha has 30 percent of 300, which is 90, so the pass mark is 105. Bala has 45 percent of 300, which is 135, and that is 30 above 105.",
      W("l6", "30% of 300 = 90"), W("l7", "90 + 15 = 105"), W("l8", "45% of 300 = 135"), W("l9", "105 + 30 = 135")),
    B("So when two people are compared with the same mark: find the gap between them in marks, and the same gap in percent, and match the two."),
)

# Rs 1,500: 20% off then 5% tax, or 5% tax then 20% off.
LESSONS[P + "PERCENTAGE_007"] = LESSON(
    B("A school bag has a marked price of 1500 rupees. Shop A takes 20 percent off and then adds 5 percent tax. Shop B adds 5 percent tax first and then takes 20 percent off. What does each shop charge?",
      GIVEN("q", "Marked price ₹1,500."), GIVEN("q2", "Shop A: 20% off, then 5% tax. Shop B: 5% tax, then 20% off")),
    B("Let's follow Shop A first. 20 percent is one fifth, and 1500 divided by 5 is 300. Taking 300 off 1500 leaves 1200 rupees.",
      W("l1", "20% of 1,500 = 300"), W("l2", "1,500 − 300 = 1,200")),
    B("Now Shop A adds 5 percent tax. It is 5 percent of which amount?",
      ask=CHOOSE(["of 1,500", "of 1,200", "of 300"], 1,
                 "Shop A adds its tax after the discount. So the tax is worked out on the reduced price, which is 1200.")),
    B("5 percent of 1200 is 60. So Shop A charges 1200 plus 60, which is 1260 rupees.",
      W("l3", "5% of 1,200 = 60"), W("l4", "1,200 + 60 = 1,260")),
    B("Now Shop B, the other way round. Tax first: 5 percent of 1500 is 75, making 1575 rupees.",
      W("l5", "5% of 1,500 = 75"), W("l6", "1,500 + 75 = 1,575")),
    B("Then 20 percent off. One fifth of 1575 is 315, and 1575 minus 315 is 1260. Shop B charges 1260 rupees too!",
      W("l7", "1,575 ÷ 5 = 315"), W("l8", "1,575 − 315 = 1,260")),
    B("So both shops charge 1260 rupees.",
      *ANSL("l9", "Both shops charge ₹1,260.", "₹1,260")),
    B("Why the same? Taking 20 percent off is a multiplication, and so is adding 5 percent. Two multiplications give the same result in either order, just as 2 times 3 is 3 times 2."),
    B("The trap is to take 5 from 20 and call it 15 percent off. That would give 1275. The two percents are of different amounts, so they cannot be subtracted.",
      W("l10", "1,500 − 15% of 1,500 = 1,275")),
    B("So a discount and a tax can come in either order, and both shops charge 1260 rupees. But always work them out one after the other."),
)

# Bill Rs 1,155 includes 5% tax on the food price.
LESSONS[P + "PERCENTAGE_008"] = LESSON(
    B("A restaurant bill of 1155 rupees already includes a 5 percent tax on the price of the food. How many rupees of tax are in the bill?",
      GIVEN("q", "Bill: ₹1,155, including 5% tax on the food price. Tax?")),
    B("The tax is 5 percent. But 5 percent of what?",
      ask=CHOOSE(["of the bill, 1,155", "of the food price", "of 1,000"], 1,
                 "The question says the tax is on the price of the food. The bill is bigger than the food price, because the tax is already inside it.")),
    B("So taking 5 percent of 1155 is the trap. The bill is the food price and the tax together.",
      UL("q", "on the food price")),
    B("The food price is the whole, 100 percent. The tax adds 5 percent more. So the bill is 105 percent of the food price.",
      W("l1", "100% + 5% = 105%")),
    B("105 percent is 1155 rupees. Now, 105 times 10 is 1050, and one more 105 makes 1155. So 1155 divided by 105 is 11, and 1 percent is 11 rupees.",
      W("l2", "105 × 10 = 1,050"), W("l3", "1,050 + 105 = 1,155"), W("l4", "1,155 ÷ 105 = 11")),
    B("1 percent of the food price is 11 rupees, and the tax is 5 percent. Which sum gives the tax?",
      ask=CHOOSE(["11 × 5", "11 × 105", "11 × 100"], 0,
                 "The tax is 5 of those 1 percent pieces, and each piece is 11 rupees.")),
    B("11 times 5 is 55. The tax in the bill is 55 rupees.",
      *ANSC("l5", "11 × 5 = 55", 55)),
    B("Check. The food is 100 percent, which is 11 times 100, or 1100 rupees. And 1100 plus 55 is 1155, the bill.",
      W("l6", "11 × 100 = 1,100"), W("l7", "1,100 + 55 = 1,155")),
    B("So when tax is already inside a bill, the bill is more than 100 percent of the price. Find 1 percent first, then take what you need."),
)
