from authored_03_lib import ANSC, ANSL, B, CHOOSE, CIRC, GIVEN, LB, LESSON, NOTE, P, STRIKE, UL, W  # noqa: F401

LESSONS = {}

ONES = "I, II, III, IV, V, VI, VII, VIII, IX"

# Greatest 5-digit even number, digits different, minus smallest 5-digit odd one.
LESSONS[P + "PLACEVALUE_001"] = LESSON(
    B("Find the difference between the greatest 5 digit even number with all its digits different, and the smallest 5 digit odd number with all its digits different.",
      GIVEN("q", "Greatest 5-digit even number, all digits different,"), GIVEN("q2", "minus smallest 5-digit odd number, all digits different")),
    B("There are two numbers to build, and each has two conditions. Let's build each one a place at a time, and subtract at the end."),
    B("The greatest 5 digit number with different digits uses the biggest digits in order: 98,765.",
      LB("l1", "Greatest, digits different: 98,765")),
    B("But look at the last digit of 98,765. Is the number even?",
      ask=CHOOSE(["yes, it is even", "no, it is odd"], 1,
                 "A number is even when its last digit is 0, 2, 4, 6 or 8. This one ends in 5, so it is odd.")),
    B("So we change only the ones digit, and as little as we can. The next even digit below 5 is 4, and 4 is not used yet. That gives 98,764.",
      STRIKE("l1", "5", "4"), LB("l2", "Greatest even: 98,764")),
    B("Now the smallest. The first digit cannot be 0, so start with 1. Then 0 can come next, and then 2, 3 and 4. That gives 10,234.",
      LB("l3", "Smallest, digits different: 10,234")),
    B("10,234 ends in 4, so it is even, and we need odd. Which is the smallest odd number we can make by changing the ones digit?",
      ask=CHOOSE(["10,231", "10,233", "10,235"], 2,
                 "The digits must all be different. 1 and 3 are already used in the number, so the smallest odd digit still free is 5.")),
    B("The ones digit becomes 5, so the smallest odd one is 10,235. Forgetting that 0 can sit in the second place, or forgetting even and odd, are the traps here.",
      STRIKE("l3", "4", "5"), LB("l4", "Smallest odd: 10,235")),
    B("Now subtract. 98,764 minus 10,235 is 88,529.",
      *ANSC("l5", "98,764 − 10,235 = 88,529", "88,529")),
    B("Check by adding back: 88,529 plus 10,235 is 98,764.",
      W("l6", "88,529 + 10,235 = 98,764")),
    B("So when a number has two conditions: build the best number for one, then nudge the last digit until the other fits too."),
)

# Thousands digit 4; swapping thousands and tens adds 2,970: the tens digit.
LESSONS[P + "PLACEVALUE_002"] = LESSON(
    B("In a 5 digit number, the thousands digit is 4. When the thousands digit and the tens digit swap places, the number becomes greater by 2970. What is the tens digit of the original number?",
      GIVEN("q", "5-digit number, thousands digit 4."), GIVEN("q2", "Swap thousands and tens digits: greater by 2,970.")),
    B("When two digits swap, only those two places change. The other three digits stay exactly as they are."),
    B("Try a small case first. Suppose the tens digit is just 1 more than the thousands digit. After the swap, the thousands place gains 1, worth 1000, and the tens place loses 1, worth 10.",
      LB("l1", "thousands: + 1000      tens: − 10")),
    B("1000 minus 10 is 990. So every 1 of difference between the two digits changes the number by 990.",
      W("l2", "1000 − 10 = 990")),
    B("Our number grew by 2970. How do we find how far apart the two digits are?",
      ask=CHOOSE(["2,970 ÷ 990", "2,970 − 990", "2,970 ÷ 1,000"], 0,
                 "Each 1 of difference between the digits is worth 990. So we count how many lots of 990 there are in 2970.")),
    B("990 times 3 is 2970, so 2970 divided by 990 is 3. The two digits are 3 apart.",
      W("l3", "990 × 3 = 2,970"), W("l4", "2,970 ÷ 990 = 3")),
    B("The digits are 3 apart, the thousands digit is 4, and the number got greater after the swap. So what is the tens digit?",
      ask=CHOOSE(["4 − 3 = 1", "4 + 3 = 7", "3"], 1,
                 "The number grew, so a bigger digit moved up into the thousands place. The tens digit must be the bigger one: 3 more than 4.")),
    B("A bigger digit moved up to the thousands place, so the tens digit is the bigger one. 4 plus 3 is 7. The tens digit is 7.",
      *ANSC("l5", "4 + 3 = 7", 7)),
    B("The trap is to stop at 3. That is the gap between the two digits, not the digit itself."),
    B("Check with a number like 54,372. Swap the 4 and the 7 and you get 57,342. And 57,342 minus 54,372 is 2970.",
      W("l6", "57,342 − 54,372 = 2,970")),
    B("So when two digits swap, find what 1 of difference is worth, then see how many of those fit into the change."),
)

# 45 million 6 thousand + 9 lakh 95 thousand, in the Indian system.
LESSONS[P + "PLACEVALUE_003"] = LESSON(
    B("A dairy sold 45 million 6 thousand packets of milk last year. This year it sold 9 lakh 95 thousand more. How many packets did it sell this year, in the Indian system?",
      GIVEN("q", "Last year: 45 million 6 thousand packets."), GIVEN("q2", "This year: 9 lakh 95 thousand more. Indian system?")),
    B("One number is in millions and the other is in lakhs. Before we add, both must be in the same system."),
    B("How many lakhs make 1 million?",
      ask=CHOOSE(["1 lakh", "10 lakh", "100 lakh"], 1,
                 "1 lakh is 1 followed by 5 zeros. 1 million is 1 followed by 6 zeros, which is 10 times as much.")),
    B("1 million is 10 lakh. So 45 million is 45 times 10, which is 450 lakh.",
      LB("l1", "1 million = 10 lakh"), W("l2", "45 × 10 = 450")),
    B("And 100 lakh make 1 crore, so 450 lakh is 4 crore 50 lakh. Reading 45 million as 45 lakh, or as 45 crore, is the big trap.",
      LB("l3", "100 lakh = 1 crore"), LB("l4", "450 lakh = 4 crore 50 lakh")),
    B("So last year's number is 4 crore 50 lakh 6 thousand.",
      LB("l5", "Last year: 4 crore 50 lakh 6 thousand")),
    B("Now add 9 lakh 95 thousand. Start with the thousands: 6 plus 95 is 101 thousand.",
      W("l6", "6 + 95 = 101"), NOTE("l6", "101", "thousand")),
    B("101 thousand is more than 100 thousand. What do we do with it?",
      ask=CHOOSE(["leave it as 101 thousand", "write 1 lakh 1 thousand", "drop the extra 1"], 1,
                 "100 thousand make 1 lakh. So 101 thousand is 1 lakh and 1 thousand, and the 1 lakh is carried over to the lakhs.")),
    B("101 thousand is 1 lakh 1 thousand. We keep the 1 thousand and carry the 1 lakh.",
      LB("l7", "101 thousand = 1 lakh 1 thousand")),
    B("Now the lakhs: 50 plus 9, plus the 1 we carried, is 60 lakh. Missing that carried lakh is the other trap.",
      W("l8", "50 + 9 + 1 = 60"), NOTE("l8", "60", "lakh")),
    B("The crores stay at 4. So this year the dairy sold 4 crore 60 lakh 1 thousand packets.",
      *ANSL("l9", "4 crore 60 lakh 1 thousand", "4 crore 60 lakh 1 thousand")),
    B("Here is the same sum written in figures, and it agrees.",
      W("l10", "4,50,06,000 + 9,95,000 = 4,60,01,000")),
    B("So put both numbers into one system, add place by place from the right, and carry when a place fills up. The answer is 4 crore 60 lakh 1 thousand."),
)

# 1 to 100 in Roman numerals: which needs the most letters?
LESSONS[P + "PLACEVALUE_004"] = LESSON(
    B("Every whole number from 1 to 100 is written in Roman numerals. Which number needs the most letters?",
      GIVEN("q", "1 to 100 in Roman numerals. Most letters?")),
    B("A bigger number does not always need more letters. 100 is just C, a single letter! So let's look at the ones part and the tens part separately."),
    B("Here are the ones, from 1 to 9.",
      LB("l1", ONES)),
    B("Which of the ones is the longest?",
      ask=CHOOSE(["9, which is IX", "8, which is VIII", "3, which is III"], 1,
                 "Count the letters. VIII has 4 letters. IX stands for a bigger number but has only 2 letters.")),
    B("8 is the longest: VIII has 4 letters.",
      CIRC("l1", "VIII")),
    B("Now here are the tens, written the same way.",
      LB("l2", "X, XX, XXX, XL, L, LX, LXX, LXXX, XC")),
    B("Which of the tens is the longest?",
      ask=CHOOSE(["90, which is XC", "80, which is LXXX", "30, which is XXX"], 1,
                 "Count the letters again. LXXX has 4 letters. 90 is short: it is only XC, which is 2 letters.")),
    B("80 is the longest: LXXX has 4 letters. And 90 is short, only XC. That is why 99 is not the answer: it is XCIX, just 4 letters.",
      CIRC("l2", "LXXX"), LB("l3", "99 = XCIX")),
    B("Join the longest tens to the longest ones. 80 and 8 make 88, which is LXXXVIII.",
      *ANSL("l4", "88 = LXXXVIII", "88")),
    B("Count them: 4 letters and 4 letters make 8 letters. No other number up to 100 has as many.",
      W("l5", "4 + 4 = 8")),
    B("So bigger does not mean longer. Split the number into its parts and find the longest of each. The answer is 88."),
)

