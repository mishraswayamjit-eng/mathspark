# Rounded to the nearest ten: 80 and 50. Smallest possible real difference.
LESSONS[P + "PLACEVALUE_007"] = LESSON(
    B("Rounded to the nearest ten, Kabir has 80 marbles and Zoya has 50. What is the smallest possible difference between the numbers they really have?",
      GIVEN("q", "To the nearest ten: Kabir 80 marbles, Zoya 50 marbles."), GIVEN("q2", "Smallest possible real difference?")),
    B("The tempting answer is 80 minus 50, which is 30. But those are rounded numbers, and each one hides a whole range of real numbers.",
      W("l1", "80 − 50 = 30")),
    B("The numbers that round to 80 run from 75 up to 84.",
      LB("k", "Kabir: 75 to 84")),
    B("And which numbers round to 50?",
      ask=CHOOSE(["45 to 54", "45 to 55", "40 to 60"], 0,
                 "It is the same pattern as Kabir's. 45 rounds up to 50, and so does everything up to 54. But 55 rounds up to 60.")),
    B("Zoya could have anything from 45 to 54. Not 55, because 55 rounds up to 60.",
      LB("z", "Zoya: 45 to 54")),
    B("For the smallest difference we want the two children as close together as possible. Which real numbers do we choose?",
      ask=CHOOSE(["Kabir 84, Zoya 45", "Kabir 75, Zoya 54", "Kabir 80, Zoya 50"], 1,
                 "Kabir has more, so bring him down as low as he can go. Zoya has fewer, so bring her up as high as she can go.")),
    B("Kabir's smallest is 75, and Zoya's greatest is 54.",
      CIRC("k", "75"), CIRC("z", "54")),
    B("75 minus 54 is 21. The smallest possible difference is 21 marbles.",
      *ANSC("l2", "75 − 54 = 21", 21)),
    B("For comparison, the greatest difference would be 84 minus 45, which is 39. So the real difference could be anywhere from 21 to 39, not just 30.",
      W("l3", "84 − 45 = 39")),
    B("So a rounded number stands for a range. For the smallest difference, take the bottom of the bigger range and the top of the smaller one."),
)

# Writing 1 to 200: how many times is the digit 7 written?
LESSONS[P + "PLACEVALUE_008"] = LESSON(
    B("Anaya writes every whole number from 1 to 200. How many times does she write the digit 7?",
      GIVEN("q", "Write every number from 1 to 200. How many 7s?")),
    B("We are counting digits, not numbers. A number like 77 has two sevens in it. So let's count one place at a time.",
      LB("l0", "77 has two 7s")),
    B("The ones place first: 7, 17, 27, and so on, up to 197.",
      LB("l1", "Ones place: 7, 17, 27, ... 197")),
    B("There is one of these in every 10 numbers. So how many are there up to 200?",
      ask=CHOOSE(["10", "20", "19"], 1,
                 "Every block of 10 numbers has exactly one number that ends in 7. And 200 is 20 blocks of 10.")),
    B("200 divided by 10 is 20. So she writes 7 in the ones place 20 times.",
      W("l2", "200 ÷ 10 = 20")),
    B("Now the tens place. 7 is the tens digit in 70 to 79, and again in 170 to 179.",
      LB("l3", "Tens place: 70 to 79, 170 to 179")),
    B("That is 10 numbers, and 10 more. So she writes 7 in the tens place 20 times as well.",
      W("l4", "10 + 10 = 20")),
    B("And the hundreds place? Up to 200 the hundreds digit is only ever 1 or 2, so there are no sevens there."),
    B("The number 77 is in both of our lists. Should we take 1 off, so that it is not counted twice?",
      ask=CHOOSE(["yes, take 1 off", "no, 77 has two sevens"], 1,
                 "We are counting every 7 that she writes. In 77 she writes the digit 7 twice, once for the tens and once for the ones.")),
    B("77 and 177 each have two sevens, so being in both lists is exactly right. 20 plus 20 is 40.",
      LB("l4a", "77 and 177: two 7s each"), *ANSC("l5", "20 + 20 = 40", 40)),
    B("So to count how often a digit is written, go place by place and add. Anaya writes the digit 7 a total of 40 times."),
)
