def bar(labels, shaded, brace, note=None):
    """A bar model of equal parts; the first `shaded` parts are coloured."""
    segs = [{"units": 1, "label": lab, "tone": "a" if i < shaded else "b"} for i, lab in enumerate(labels)]
    spec = {"kind": "barModel", "bars": [{"segments": segs, "brace": brace}]}
    if note:
        spec["note"] = note
    return spec


