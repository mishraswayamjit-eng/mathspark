# 56 apples. Takes out 4 apples at a time, replaces with 3 oranges. Oranges in the end?
LESSONS["EXT_G5_WS_B3_025"] = lesson(
    beat("A basket has 56 apples. Amey takes out 4 apples at a time and puts 3 oranges in their place, until no apples are left. How many oranges are there at the end?",
         G("q1", "56 apples. Each turn: 4 apples out, 3 oranges in."), G("q2", "Oranges at the end = ?")),
    beat("Each turn is a swap: 4 apples out, 3 oranges in. Watch the first few turns in this table.",
         F(table(["turn", "apples left", "oranges"], [["1", "52", "3"], ["2", "48", "6"], ["3", "44", "9"]]))),
    beat("The oranges go up by 3 on every turn. So if we know the number of turns, we know the oranges. The turns are the key."),
    beat("How many turns does it take to remove all 56 apples?",
         ask=ask(["56 ÷ 3", "56 ÷ 4", "56 − 4"], 1,
                 "Apples leave 4 at a time. So the number of turns is how many times 4 goes into 56.")),
    beat("56 divided by 4 is 14. So Amey makes 14 swaps.",
         W("w1", "56 ÷ 4 = 14")),
    beat("Each of the 14 turns puts in 3 oranges. So how do we find the oranges?",
         ask=ask(["14 × 3", "14 + 3", "56 − 3"], 0,
                 "3 oranges go in on every turn, and there are 14 turns. 14 lots of 3 means multiply.")),
    beat("14 times 3 is 42.",
         W("w2", "14 × 3 = 42")),
    beat("So there are 42 oranges in the basket at the end.",
         A("ans", "42 oranges"), C("ans", "42 oranges")),
    beat("Does that make sense? Each swap puts in one fruit fewer than it takes out. 14 swaps, so 14 fewer fruits, and 56 minus 14 is 42. Yes.",
         W("c1", "56 − 14 = 42")),
    beat("So when something happens again and again, first count how many times it happens. Then multiply."),
)

# Four years hence, Siya will be 3 years older than Diya. Sum of present ages 35. Siya now?
LESSONS["EXT_G5_WS_B3_028"] = lesson(
    beat("Four years from now, Siya will be 3 years older than Diya. Today their ages add up to 35. How old is Siya now?",
         G("q1", "In 4 years Siya will be 3 years older than Diya"), G("q2", "Now: Siya + Diya = 35 years. Siya now = ?")),
    beat("In four years, Siya will be 3 years older than Diya. So how much older is she today?",
         ask=ask(["7 years older", "3 years older", "1 year younger"], 1,
                 "Both girls grow older together, one year every year. So the gap between them never changes. It is 3 years today as well.")),
    beat("Say it with me: the gap between two ages never changes. So Siya is 3 years older today too, and the four years was only there to distract us.",
         X("q1", "In 4 years", "gap is always 3")),
    beat("Now draw it. Diya's bar, and Siya's bar, which is the same length plus an extra 3. Together they make 35.",
         F(bars(bar("Diya", [seg("?", 4, "a")]),
                bar("Siya", [seg("?", 4, "a"), seg("3", 1, "c")]),
                note="Together the bars make 35 years"))),
    beat("Snip off Siya's extra 3, and what is left is two equal bars. 35 minus 3 is 32.",
         W("w1", "35 − 3 = 32")),
    beat("Those 32 years are two equal bars, and each one is Diya's age. How do we find Diya's age?",
         ask=ask(["32 − 2", "35 ÷ 2", "32 ÷ 2"], 2,
                 "Two equal bars make 32, so one bar is half of 32.")),
    beat("32 divided by 2 is 16. Diya is 16. But careful, the question asks for Siya!",
         W("w2", "32 ÷ 2 = 16")),
    beat("Siya is 3 years older than Diya. 16 plus 3 is 19.",
         W("w3", "16 + 3 = 19")),
    beat("So Siya is 19 years old now.",
         A("ans", "Siya is 19 years old"), C("ans", "19 years")),
    beat("Check both clues. 19 plus 16 is 35, the sum. And 19 minus 16 is 3, the gap. Both work.",
         W("c1", "19 + 16 = 35"), W("c2", "19 − 16 = 3")),
    beat("So when you know a sum and a gap: take the gap off, halve what is left, and add the gap back for the older one."),
)

