# A factory makes 1720 boxes every day. Total production in July?
LESSONS["EXT_G5_WS_B3_005"] = lesson(
    beat("A factory makes 1720 boxes every day. What is its total production in the month of July?",
         G("q", "1720 boxes every day. Total in July = ?")),
    beat("One number seems to be missing. To find the total for July, what else do we need to know?",
         U("q", "July"),
         ask=ask(["the days in July: 30", "the days in July: 31", "the weeks in July: 4"], 1,
                 "July is one of the long months, with 31 days. On your knuckles, July lands on a knuckle, and knuckle months have 31.")),
    beat("So the factory makes 1720 boxes, 31 times over. That is 1720 times 31. A big sum, so let's break the 31 into 30 and 1.",
         Lb("w0", "July = 31 days")),
    beat("First the 30 days. 1720 times 3 is 5160. Put a zero on the end for times 30, and we have 51600.",
         W("w1", "1720 × 3 = 5160"), W("w2", "1720 × 30 = 51600")),
    beat("Now the 1 extra day: 1720 more boxes. This is the day children forget!",
         W("w3", "1720 × 1 = 1720")),
    beat("Add the two parts. 51600 plus 1720 is 53320.",
         W("w4", "51600 + 1720 = 53320")),
    beat("So in July the factory makes 53320 boxes.",
         AM("ans", "1720 × 31 = 53320"), C("ans", "53320")),
    beat("Check. Take one day's boxes off our answer: 53320 minus 1720 is 51600, exactly the 30 days we began with.",
         W("c1", "53320 − 1720 = 51600")),
    beat("The trap is to use 30 days and stop at 51600. So know your months, and split a hard multiplication into easy pieces."),
)

# 12.5 kg of sweets distributed equally amongst 25 students (17 girls). Each boy receives?
LESSONS["EXT_G5_WS_B3_013"] = lesson(
    beat("12.5 kilograms of sweets are shared equally among 25 students. 17 of them are girls and the rest are boys. How much does each boy get?",
         G("q1", "12.5 kg of sweets shared equally by 25 students"), G("q2", "17 girls, the rest boys. Each boy gets = ?")),
    beat("Read one word again: equally. So does a boy get more than a girl, less, or the same?",
         U("q1", "equally"),
         ask=ask(["more than a girl", "the same as a girl", "less than a girl"], 1,
                 "Equally means every student gets the same amount, whether a boy or a girl.")),
    beat("So each boy gets the same as any other student. That means the 17 girls is extra information. We don't need it at all.",
         X("q2", "17 girls", "not needed")),
    beat("Now the sharing. 12.5 kilograms among 25 is awkward, so let's change to grams. 1 kilogram is 1000 grams, so 12.5 kilograms is 12500 grams.",
         W("w1", "12.5 × 1000 = 12500"), Lb("w2", "12.5 kg = 12500 g")),
    beat("Among how many students do we share the 12500 grams?",
         ask=ask(["8, the boys", "17, the girls", "25, all of them"], 2,
                 "The sweets went to all 25 students, not only to the boys. So we share among 25.")),
    beat("125 divided by 25 is 5. So 12500 divided by 25 is 500.",
         W("w3", "125 ÷ 25 = 5"), W("w4", "12500 ÷ 25 = 500")),
    beat("Each boy gets 500 grams of sweets.",
         A("ans", "Each boy gets 500 g"), C("ans", "500 g")),
    beat("Check. 25 students with 500 grams each: 25 times 500 is 12500 grams, which is our 12.5 kilograms.",
         W("c1", "25 × 500 = 12500")),
    beat("Two things to keep. Watch for the word equally. And don't be afraid to leave a number unused when the question does not need it."),
)

