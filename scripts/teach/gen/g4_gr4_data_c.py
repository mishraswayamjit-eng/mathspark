L["G4A_DATA_028"] = [
    beat("The rainfall in a town, in millimetres, was: Monday 6, Tuesday 10, Wednesday 4, Thursday 12, Friday 8. On how many days was the rainfall more than the average?",
         given("q", "Mon 6, Tue 10, Wed 4, Thu 12, Fri 8  (millimetres)"),
         lab("q2", "On how many days was it more than the average?"), fig(D, "G4A_DATA_028")),
    beat("There are two jobs here. First find the average. Then count the days that beat it."),
    beat("Add them up: 6 plus 10 plus 4 plus 12 plus 8 is 40.",
         w("a", "6 + 10 + 4 + 12 + 8 = 40")),
    beat("There are 5 days. 40 divided by 5 is 8. So the average is 8 millimetres.",
         w("b", "40 ÷ 5 = 8"), lab("c", "Average = 8")),
    beat("Now compare each day with 8. Tuesday's 10 is more. Thursday's 12 is more. Monday's 6 and Wednesday's 4 are less.",
         ring("q", "Tue 10"), ring("q", "Thu 12"), strike("q", "Mon 6"), strike("q", "Wed 4")),
    beat("What about Friday, with exactly 8?",
         ask=choose("it does not count", ["it counts"],
                    "Friday's 8 is equal to the average. Equal is not the same as more than. So Friday is left out.")),
    beat("Friday is equal to the average, not more than it. So Friday is out. That is the trap.",
         strike("q", "Fri 8", "equal")),
    beat("The rainfall was more than the average on 2 days.",
         ans("d", "2 days")),
    beat("More than means really bigger. Find the average first, then compare with care."),
]

L["G4A_DATA_029"] = [
    beat("Ananya's average mark in 4 tests was 18. After the 5th test, her average for all 5 tests became 20. How many marks did she get in the 5th test?",
         given("q", "4 tests: average 18.    5 tests: average 20."), lab("q2", "5th test mark = ?"),
         fig(D, "G4A_DATA_029")),
    beat("Averages hide the real marks. So we turn each average into a total. A total is the average times the number of tests.",
         lab("r", "Total = average × number of tests")),
    beat("4 tests with an average of 18. 4 times 18 is 72 marks.",
         w("a", "4 × 18 = 72")),
    beat("After 5 tests the average is 20. What is the total for all 5 tests?",
         ask=choose("100", ["80", "90"],
                    "Now there are 5 tests, not 4. So the total is 5 times 20, which is 100.")),
    beat("5 times 20 is 100 marks.",
         w("b", "5 × 20 = 100")),
    beat("The total grew from 72 to 100. That jump is the 5th test. 100 minus 72 is 28.",
         w("c", "100 − 72 = 28")),
    beat("Ananya got 28 marks in the 5th test.",
         ans("d", "28 marks")),
    beat("Why so high? The 5th test had to score 20 for itself, and also lift each of the 4 earlier tests by 2. That is 8 extra, and 20 plus 8 is 28.",
         w("e", "20 + 4 × 2 = 28")),
    beat("The trap is to just add 2 to 20. Always change averages into totals first."),
]

L["G4A_DATA_030"] = [
    beat("A pictograph shows newspapers collected. Class 4A has 7 pictures and Class 4B has 4. Each picture stands for the same number. Class 4A collected 21 more than Class 4B. How many did 4A collect?",
         given("q", "Class 4A: 7 pictures.    Class 4B: 4 pictures."),
         lab("q2", "4A collected 21 more newspapers. 4A collected = ?"), fig(D, "G4A_DATA_030")),
    beat("We are not told what one picture stands for. That is the puzzle. But there is a clue: the 21 more."),
    beat("Class 4A has 7 pictures and 4B has 4. 7 minus 4 is 3. So 4A has 3 extra pictures.",
         w("a", "7 − 4 = 3")),
    beat("Those 3 extra pictures are the 21 extra newspapers. So what does 1 picture stand for?",
         ask=choose("7 newspapers", ["21 newspapers", "3 newspapers"],
                    "3 pictures stand for 21 newspapers. Share 21 among the 3 pictures: 21 divided by 3 is 7.")),
    beat("21 divided by 3 is 7. Each picture stands for 7 newspapers.",
         w("b", "21 ÷ 3 = 7"), lab("c", "1 picture = 7 newspapers"), box("c", "7 newspapers")),
    beat("Now Class 4A. It has 7 pictures, each worth 7. 7 times 7 is 49.",
         w("d", "7 × 7 = 49")),
    beat("Class 4A collected 49 newspapers.",
         ans("e", "49 newspapers")),
    beat("Check: 4B has 4 times 7, which is 28. And 49 minus 28 is 21. It fits.",
         w("f", "4 × 7 = 28"), w("g", "49 − 28 = 21")),
    beat("When the key is missing, use the difference to find what one picture is worth."),
]

