    beat("The middle is the trap. Class 4B is bigger, so it counts for more. To be fair to every child, we use the total marks."),
    beat("Class 4A: 20 children with an average of 30. 20 times 30 is 600 marks.",
         w("a", "20 × 30 = 600")),
    beat("Class 4B: 30 children with an average of 40. 30 times 40 is 1200 marks.",
         w("b", "30 × 40 = 1200")),
    beat("Together that is 600 plus 1200, which is 1800 marks for 50 children.",
         w("c", "600 + 1200 = 1800")),
    beat("Share 1800 marks among 50 children. 1800 divided by 50 is 36, because 50 times 36 is 1800.",
         w("d", "1800 ÷ 50 = 36"), w("e", "50 × 36 = 1800")),
    beat("The average mark of all 50 children is 36.",
         ans("f", "Average = 36", "36")),
    beat("See, 36 is closer to 40 than to 30. The bigger class pulls the average towards itself. Never average two averages: go back to the totals."),
