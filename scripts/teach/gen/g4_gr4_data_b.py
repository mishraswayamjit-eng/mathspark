L["G4A_DATA_014"] = [
    beat("In a pictograph of library books, each picture stands for 5 books. Monday has 4 pictures, Tuesday has 6 and Wednesday has 3. How many books were borrowed altogether?",
         given("q", "1 picture = 5 books. Mon 4, Tue 6, Wed 3 pictures."), lab("q2", "Books altogether = ?"),
         fig(D, "G4A_DATA_014")),
    beat("Every picture is worth the same. So we can count all the pictures first, and change them into books at the end."),
    beat("4 plus 6 plus 3 is 13 pictures.",
         w("a", "4 + 6 + 3 = 13")),
    beat("13 pictures, and each one stands for 5 books. What do we do now?",
         ask=choose("13 × 5", ["13 + 5", "13 ÷ 5"],
                    "Every one of the 13 pictures stands for 5 books. 13 lots of 5 means we multiply.")),
    beat("13 times 5. 10 fives are 50, and 3 fives are 15. 50 plus 15 is 65.",
         w("b", "10 × 5 = 50"), w("c", "3 × 5 = 15"), w("d", "13 × 5 = 65")),
    beat("65 books were borrowed altogether.",
         ans("e", "65 books")),
    beat("Check day by day: 20 books, 30 books and 15 books. 20 plus 30 plus 15 is 65.",
         w("f", "20 + 30 + 15 = 65")),
    beat("13 is only the number of pictures. Always turn the pictures into books."),
]

