def A(qid, beats, check=None):
    LESSONS[qid] = lesson(beats, "authored", check)


def bar5(labels, shaded, brace):
    segs = [{"units": 1, "label": lab, "tone": "a" if i < shaded else "b"} for i, lab in enumerate(labels)]
    return {"kind": "barModel", "bars": [{"segments": segs, "brace": brace}]}


