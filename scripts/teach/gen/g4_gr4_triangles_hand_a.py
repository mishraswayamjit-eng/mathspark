# Which triangle can have angles 48° and 66°?
LESSONS["EXT_G4_FP_2020_035"] = lesson([
    B("A triangle has angles of 48 degrees and 66 degrees, and we have to name the triangle. But a triangle has 3 angles, and we only know 2.",
      G("l1", "Angles 48° and 66°. Which kind of triangle?"), QF("EXT_G4_FP_2020_035")),
    B("So before we name it, we need the third angle. What do the 3 angles of any triangle add up to?",
      ask=ch(["90°", "180°", "360°"], 1,
             "Tear the 3 corners off a paper triangle and they fit along a straight line. A straight line is 180 degrees.")),
    B("180 degrees. So first add the 2 angles we know. 48 plus 60 is 108, and 6 more is 114.",
      W("l2", "48 + 60 = 108"), W("l3", "108 + 6 = 114")),
    B("Now take 114 away from 180. 180 minus 110 is 70, and 4 less is 66. The third angle is 66 degrees.",
      W("l4", "180 − 110 = 70"), W("l5", "70 − 4 = 66"), W("l6", "180 − 114 = 66")),
    B("Now look at all 3 angles together: 48, 66 and 66. What do you notice?",
      W("l7", "Angles: 48°, 66°, 66°"),
      ask=ch(["all 3 are equal", "2 of them are equal", "one of them is 90°"], 1,
             "Look at the 66. It is there twice. So 2 of the angles are equal.")),
    B("2 equal angles! And a triangle with 2 equal angles always has 2 equal sides as well.",
      group("l7", [{"text": "66°", "nth": 1}, {"text": "66°", "nth": 2}], "equal"),
      tri("isosceles", a="48°", b="66°", c="66°", hl=["ab", "ca"])),
    B("A triangle with 2 equal sides is called isosceles. So this is an isosceles triangle.",
      ANS("l8", "Isosceles triangle")),
    B("Why not the other names? Equilateral needs 3 angles of 60. Right-angled needs a 90. Obtuse needs an angle bigger than 90. Ours has none of these.",
      W("l9", "Equilateral: 60°, 60°, 60°")),
    B("So when only 2 angles are given, always find the third before you name the triangle. The name may be hiding in it."),
])

