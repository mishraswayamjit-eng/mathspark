L["Q_CH17_015"] = [
    beat("A Cricket World Cup began on the 17th of March, a Wednesday. The final was on the second Sunday in May. On what date was the final?",
         given("q", "17th March = Wednesday. Final: second Sunday in May."), fig(T, "Q_CH17_015")),
    beat("If we know the day of the 1st of May, the rest is easy. So let's count the days from the 17th of March to the 1st of May."),
    beat("March has 31 days. How many days of March are left after the 17th?",
         lab("m", "March has 31 days"),
         ask=choose("14", ["17", "13"],
                    "Take the 17 days that have gone away from 31. 31 minus 17 is 14.")),
    beat("31 minus 17 is 14. Then come all 30 days of April, and 1 day of May. 14 plus 30 plus 1 is 45 days.",
         w("a", "31 − 17 = 14"), w("b", "14 + 30 + 1 = 45")),
    beat("6 times 7 is 42. So 45 days is 6 weeks and 3 days.",
         w("c", "6 × 7 = 42"), w("d", "45 − 42 = 3")),
    beat("6 weeks later it is Wednesday again. Then 3 more days: Thursday, Friday, Saturday. So the 1st of May is a Saturday.",
         lab("e", "1st May = Saturday")),
    beat("The 1st of May is a Saturday, so the 2nd is a Sunday. Is that the Sunday we want?",
         ask=choose("no, that is the first Sunday", ["yes, that is the final"],
                    "The 2nd of May is the very first Sunday of the month. The final is on the second Sunday, one week later.")),
    beat("The first Sunday is the 2nd. Add 7 to reach the second Sunday. 2 plus 7 is 9.",
         lab("f", "First Sunday: 2nd May"), w("g", "2 + 7 = 9")),
    beat("The final was on the 9th of May.",
         ans("h", "9th May")),
    beat("Find the day of the 1st of the month, find the first Sunday, then add sevens."),
]

L["Q_CH17_016"] = [
    beat("In 2003, April Fools' Day, the 1st of April, was on a Tuesday. On which day was it in 2004?",
         given("q", "1st April 2003 = Tuesday. 1st April 2004 = ?"), fig(T, "Q_CH17_016")),
    beat("From the 1st of April 2003 to the 1st of April 2004 is one full year. Usually a year moves the day on by 1. But let's check for a leap day."),
    beat("2004 is a leap year. Its leap day is the 29th of February 2004. Is that between April 2003 and April 2004?",
         lab("a", "Leap day: 29 February 2004"),
         ask=choose("yes, it is in between", ["no, it comes later"],
                    "February 2004 comes after April 2003 and before April 2004. So the leap day is inside our year.")),
    beat("The leap day is inside, so this stretch has 366 days, one more than usual.",
         lab("b", "April 2003 → April 2004: 366 days"), box("b", "366 days")),
    beat("52 weeks make 364 days. So 366 days is 52 weeks and 2 days.",
         w("c", "52 × 7 = 364"), w("d", "366 − 364 = 2")),
    beat("Full weeks bring us back to Tuesday. Only the 2 extra days matter: Tuesday, then Wednesday, then Thursday.",
         lab("e", "Tue → Wed → Thu")),
    beat("In 2004, April Fools' Day was on a Thursday.",
         ans("f", "1st April 2004 = Thursday", "Thursday")),
    beat("This is the trap: an ordinary year moves the day by 1, but a leap day in between makes it 2."),
]

