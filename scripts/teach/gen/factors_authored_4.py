# The difference of the LCM and HCF of 12, 60 and 120 is twice a number.
LESSONS["EXT_G5_WS_B6_006"] = LESSON(
    B("We need the L C M and the H C F of 12, 60 and 120. Their difference is twice a mystery number.",
      GIVEN("q", "LCM − HCF of 12, 60, 120 = 2 × ?")),
    B("Look at these three numbers before doing any work. 60 is 12 times 5, and 120 is 12 times 10.",
      W("a", "60 = 12 × 5"), W("b", "120 = 12 × 10")),
    B("So 12 divides all three numbers. And nothing bigger than 12 can divide 12. What is the H C F?",
      ask=CHOOSE(["2", "12", "60"], 1,
                 "The H C F cannot be bigger than the smallest number, 12. And 12 itself divides all three. So the H C F is 12.")),
    B("So the H C F is 12, the smallest of the three numbers.",
      LB("h", "HCF = 12")),
    B("Now the L C M. 120 is in the 12 times table, and in the 60 times table too. And it is the very first number in its own table, so the L C M is 120.",
      W("c", "120 = 60 × 2"), LB("l", "LCM = 120")),
    B("The difference is 120 minus 12, which is 108.",
      W("d", "120 − 12 = 108")),
    B("The question says 108 is twice a number. How do we find that number?",
      ask=CHOOSE(["Double 108", "Take 2 away from 108", "Halve 108"], 2,
                 "Twice a number means 2 times the number. To undo times 2, we divide by 2.")),
    B("Half of 108 is 54. So the number is 54.",
      W("e", "108 ÷ 2 = 54"), ANS("ans", "The number = 54"), CIRC("ans", "54")),
    B("Check: twice 54 is 108, and 108 is 120 minus 12.",
      W("k", "2 × 54 = 108")),
    B("Worth remembering: when one number divides all the others, it is the H C F. When one number is a multiple of all the others, it is the L C M."),
)

