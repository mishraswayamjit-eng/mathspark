# Which statement is true for every triangle?
_A = "A: Its largest angle is more than 60°"
_B = "B: It has at least two acute angles"
_C = "C: Its two smallest angles add up to less than 90°"
_D = "D: Exactly one of its angles is 60° or more"
LESSONS["G4A_TRIANGLES_023"] = lesson([
    B("4 statements. Only 1 of them is true for every triangle there is. Which one?",
      G("l1", "Which statement is true for EVERY triangle?"),
      W("la", _A, tone="given"), W("lb", _B, tone="given"), W("lc", _C, tone="given"), W("ld", _D, tone="given")),
    B("True for every triangle is a strong claim. If we find even 1 triangle that breaks a statement, that statement is out. So let's hunt for rule breakers."),
    B("A good triangle to test with is the equilateral one. Its angles are 60, 60 and 60.",
      W("l2", "Equilateral: 60°, 60°, 60°"), tri("equilateral", a="60°", b="60°", c="60°")),
    B("Statement A says the largest angle is more than 60. Does the equilateral triangle obey?",
      ask=ch(["yes, it does", "no, its largest is exactly 60°"], 1,
             "In the equilateral triangle the largest angle is 60. That is equal to 60, not more than 60. So it breaks statement A.")),
    B("It breaks A. It breaks C too: its 2 smallest angles make 60 plus 60, which is 120. That is far more than 90.",
      W("l3", "60 + 60 = 120 > 90"), strike("la", _A), strike("lc", _C)),
    B("Now D: exactly one angle of 60 or more. Try a triangle with angles 40, 70 and 70. It has 2 angles above 60. D is broken.",
      W("l4", "40 + 70 + 70 = 180"), strike("ld", _D)),
    B("Only B is left. But can it ever be broken? An acute angle is less than 90. Could a triangle have 2 angles that are 90 or more?",
      W("l5", "90 + 90 = 180"),
      ask=ch(["no, they would use up all 180°", "yes, easily"], 0,
             "2 angles of 90 or more add up to at least 180. That leaves nothing for the third angle.")),
    B("So at most 1 angle can be 90 or more. The other 2 must be acute, every single time."),
    B("So the statement that is true for every triangle is B: it has at least 2 acute angles.",
      ANS("l6", "B: at least two acute angles", "B")),
    B("To knock out an always statement, find 1 rule breaker. To keep one, show why it can never be broken."),
])

