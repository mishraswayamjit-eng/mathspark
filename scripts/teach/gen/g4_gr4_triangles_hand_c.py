# A 12 cm straw cut into three whole-number pieces. How many triangles?
LESSONS["G4A_TRIANGLES_016"] = lesson([
    B("Meera cuts a 12 centimetre straw into 3 pieces, each a whole number of centimetres, and makes a triangle. How many different triangles can she make?",
      G("l1", "A 12 cm straw is cut into 3 whole-number pieces."), W("l2", "How many different triangles?", tone="given"),
      QF("G4A_TRIANGLES_016")),
    B("The 3 pieces add up to 12. But they must also close into a triangle: the 2 shorter pieces together must be longer than the longest one.",
      W("l3", "2 shorter pieces together > longest piece")),
    B("Could the longest piece be 6 centimetres?",
      W("l4", "12 − 6 = 6"),
      ask=ch(["yes, that is fine", "no, the other 2 only make 6"], 1,
             "If the longest piece is 6, the other 2 share the 6 that is left. They would be exactly as long as the long piece, and lie flat.")),
    B("So the longest piece must be shorter than 6, which is half the straw. It can be 5 at most.",
      W("l5", "Longest piece: less than 6 cm")),
    B("Longest piece 5. The other 2 share 7. They can be 2 and 5, or 3 and 4. Not 1 and 6, because then the 6 would be the longest.",
      W("l6", "12 − 5 = 7"), W("t1", "2, 5, 5"), W("t2", "3, 4, 5")),
    B("Longest piece 4. The other 2 share 8, and neither may be longer than 4. What must they be?",
      W("l7", "12 − 4 = 8"),
      ask=ch(["4 and 4", "3 and 5", "2 and 6"], 0,
             "Neither piece may be longer than 4, and together they must make 8. Only 4 and 4 does that.")),
    B("4 and 4. So the triangle is 4, 4, 4, an equilateral one.",
      W("t3", "4, 4, 4")),
    B("Longest piece 3? Then 3 pieces of 3 or less make 9 at most. That cannot reach 12. So the list is complete.",
      W("l8", "3 + 3 + 3 = 9 < 12")),
    B("Count them: 2, 5, 5 and 3, 4, 5 and 4, 4, 4. That makes 3 triangles.",
      ANS("l9", "3 triangles")),
    B("The secret was to work in order, from the longest piece down. That way nothing is missed, and nothing is counted twice."),
])

