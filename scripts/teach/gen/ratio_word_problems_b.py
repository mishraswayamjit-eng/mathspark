# A man earned Rs.120 when he sold 8 dozens of mangoes. How much for 20 dozens?
LESSONS["EXT_G5_FP_2020_009"] = lesson(
    beat("A man earned 120 rupees by selling 8 dozen mangoes. How much would he earn by selling 20 dozen?",
         G("q1", "8 dozen mangoes sold: earns ₹120"), G("q2", "20 dozen sold: earns ₹ ?")),
    beat("More dozens sold, more rupees earned. So our answer must be bigger than 120.",
         F(table(["dozens", "earns"], [["8", "₹120"], ["1", "?"], ["20", "?"]]))),
    beat("8 dozen to 20 dozen is not a neat jump. What should we find first?",
         ask=ask(["20 − 8", "what he earns on 1 dozen", "the mangoes in 8 dozen"], 1,
                 "Find one first. From the earning on 1 dozen, we can reach 20 dozen, or any number of dozens.")),
    beat("120 rupees from 8 dozen. 120 divided by 8 is 15. He earns 15 rupees on each dozen.",
         W("w1", "120 ÷ 8 = 15"), Lb("w2", "1 dozen: ₹15"), U("w2", "1 dozen")),
    beat("And for 20 dozen?",
         ask=ask(["20 × 15", "20 + 15", "120 ÷ 20"], 0,
                 "20 dozens, each earning 15 rupees. 20 lots of 15 means multiply.")),
    beat("2 times 15 is 30, so 20 times 15 is 300.",
         W("w3", "2 × 15 = 30"), W("w4", "20 × 15 = 300")),
    beat("He would earn 300 rupees.",
         A("ans", "20 dozen: ₹300"), C("ans", "₹300")),
    beat("Check by a different path. 4 dozen is half of 8 dozen, so it earns half of 120, which is 60. 20 dozen is 5 lots of 4 dozen, and 5 times 60 is 300.",
         W("c1", "120 ÷ 2 = 60"), W("c2", "5 × 60 = 300")),
    beat("Find one, then find many. And notice we stayed in dozens the whole way, because the question did."),
)

# Work to be completed in 30 days for Rs.27000. He works for 18 days and leaves. How much to pay him?
LESSONS["EXT_G5_FP_2020_024"] = lesson(
    beat("A man agrees to do a job in 30 days for 27,000 rupees. But he works for 18 days and then leaves. How much should he be paid?",
         G("q1", "30 days of work for ₹27,000"), G("q2", "He works only 18 days. Fair pay = ₹ ?")),
    beat("What is fair? He should be paid for the days he worked, and not for the days he did not.",
         F(bars(bar(None, [seg("18 days worked", 3.6, "a"), seg("not worked", 2.4, "unknown")], brace="30 days: ₹27,000")))),
    beat("To pay him fairly, what should we find first?",
         ask=ask(["27,000 ÷ 18", "his pay for 1 day", "27,000 − 18"], 1,
                 "The 27,000 rupees is for all 30 days. So first we find the pay for 1 day.")),
    beat("27,000 divided by 30 is 900, so one day of work earns 900 rupees. Careful: we divide by 30, the days the money was meant for, not by 18.",
         W("w1", "27000 ÷ 30 = 900"), Lb("w2", "1 day: ₹900"), U("w2", "1 day")),
    beat("He worked 18 days. So what do we work out?",
         ask=ask(["18 × 900", "30 × 900", "900 ÷ 18"], 0,
                 "He earns 900 rupees for each day he worked, and he worked 18 days. So it is 18 times 900.")),
    beat("18 times 9 is 162, so 18 times 900 is 16,200.",
         W("w3", "18 × 9 = 162"), W("w4", "18 × 900 = 16200")),
    beat("A fair employer pays him 16,200 rupees.",
         A("ans", "Pay for 18 days = ₹16,200"), C("ans", "₹16,200")),
    beat("Check. He missed 30 minus 18, that is 12 days, worth 12 times 900, which is 10,800 rupees. And 16,200 plus 10,800 is 27,000.",
         W("c1", "30 − 18 = 12"), W("c2", "12 × 900 = 10800"), W("c3", "16200 + 10800 = 27000")),
    beat("So for part of a job: find the pay for one day, then multiply by the days really worked."),
)

