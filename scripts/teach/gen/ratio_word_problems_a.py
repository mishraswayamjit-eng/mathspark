# A worker is paid Rs.3 per hour up to 40 hours. Overtime is twice the payment. Paid Rs.168. Overtime hours?
LESSONS["EXT_G5_FP_2016_007"] = lesson(
    beat("A worker earns 3 rupees an hour for his first 40 hours. After that comes overtime, which pays twice as much. In all he was paid 168 rupees.",
         G("q1", "₹3 an hour for the first 40 hours"), G("q2", "Overtime pays twice as much. Total pay ₹168")),
    beat("What are we hunting for? The number of overtime hours. So picture his pay as one bar with two pieces: regular pay and overtime pay.",
         F(bars(bar(None, [seg("regular pay", 5, "a"), seg("overtime pay", 2, "unknown")], brace="₹168")))),
    beat("Which of the two pieces can we work out straight away?",
         ask=ask(["the overtime pay", "the regular pay", "the overtime hours"], 1,
                 "We know everything about the regular time: 40 hours, at 3 rupees an hour. So we start there.")),
    beat("40 hours at 3 rupees an hour. 40 times 3 is 120, so 120 rupees is his regular pay.",
         W("w1", "40 × 3 = 120")),
    beat("The rest of the 168 rupees must be overtime pay. 168 minus 120 is 48.",
         W("w2", "168 − 120 = 48"),
         F(bars(bar(None, [seg("₹120", 5, "a"), seg("₹48", 2, "b")], brace="₹168")))),
    beat("Now, how much does one hour of overtime pay? Remember, it is twice the regular 3 rupees.",
         ask=ask(["₹6 an hour", "₹3 an hour", "₹5 an hour"], 0,
                 "Twice means 2 times. 2 times 3 rupees is 6 rupees for each overtime hour.")),
    beat("2 times 3 is 6. Careful here: the trap is to divide the 48 rupees by the regular 3. Overtime hours earn 6 rupees each.",
         W("w3", "2 × 3 = 6")),
    beat("So how many times does 6 go into 48? 48 divided by 6 is 8.",
         W("w4", "48 ÷ 6 = 8")),
    beat("He worked 8 hours of overtime.",
         A("ans", "Overtime = 8 hours"), C("ans", "8 hours")),
    beat("Check it. 8 hours at 6 rupees is 48. Add the regular 120, and we get 168, exactly what he was paid.",
         W("c1", "8 × 6 = 48"), W("c2", "120 + 48 = 168")),
    beat("So when pay comes in two parts, work out the part you know, take it away, and then deal with what is left."),
)

# If 40 gm of talc powder costs Rs.12, what is the cost of 70 gm?
LESSONS["EXT_G5_FP_2016_017"] = lesson(
    beat("40 grams of talc powder costs 12 rupees. We want the cost of 70 grams of the same powder.",
         G("q1", "40 g of talc powder costs ₹12"), G("q2", "70 g costs ₹ ?")),
    beat("Same powder, so every gram costs the same. But 70 grams is not double 40 grams, or any neat number of times 40. So there is no quick jump.",
         F(table(["grams", "cost"], [["40", "₹12"], ["1", "?"], ["70", "?"]]))),
    beat("So what is the smart thing to find first?",
         ask=ask(["the cost of 30 grams", "70 − 40", "the cost of 1 gram"], 2,
                 "When the numbers don't fit neatly, find the cost of 1 first. From 1, we can reach any number.")),
    beat("One gram costs 12 rupees shared over 40 grams. Careful: that is 12 divided by 40, not 40 divided by 12. We are sharing rupees among grams.",
         W("w1", "12 ÷ 40 = 0.30")),
    beat("12 divided by 40 is 0.30. So 1 gram costs 0.30 rupees, which is 30 paise.",
         Lb("w2", "1 g costs ₹0.30 = 30 paise"), U("w2", "1 g")),
    beat("We have one. Now, how do we get to 70 grams?",
         ask=ask(["70 × 0.30", "70 ÷ 0.30", "70 + 0.30"], 0,
                 "Each gram costs 0.30 rupees, and there are 70 of them. 70 lots of the same amount means multiply.")),
    beat("70 times 0.30 is 21. Think of it as 7 times 3.",
         W("w3", "70 × 0.30 = 21")),
    beat("So 70 grams costs 21 rupees.",
         A("ans", "70 g costs ₹21"), C("ans", "₹21")),
    beat("Check another way. 10 grams cost 10 times 0.30, which is 3 rupees. 70 grams is 7 lots of 10 grams, and 7 times 3 is 21. Same answer.",
         W("c1", "10 × 0.30 = 3"), W("c2", "7 × 3 = 21")),
    beat("That is the unitary method: find one, then find many."),
)

