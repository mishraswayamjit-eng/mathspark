LESSONS["EXT_G5_WS_01_018"] = [
    beat("We want the 23rd even number before 105. Let's start walking backwards from 105 and see what happens.",
         given("l1", "23rd even number before 105 = ?", True)),
    beat("105 is odd, so the 1st even number before it is 104. Then come 102, 100 and 98. What is the jump each time we step back?",
         words("l2", "104, 102, 100, 98, …"),
         ask=choose("− 2", ["− 1", "+ 2"],
                    "Even numbers are 2 apart. Going backwards, each one is 2 less than the one before.")),
    beat("Minus 2, every time.", jumps("l2", ["−2", "−2", "−2"])),
    beat("Now, the trap. 104 is already the 1st one. To reach the 2nd we step back once. To reach the 3rd, twice.",
         table("f1", ["Even number", "Steps from 104"], [["1st", "0"], ["2nd", "1"], ["3rd", "2"]])),
    beat("So how many steps back from 104 take us to the 23rd?",
         ask=choose("22", ["23", "24"],
                    "Look at the table. The steps are always 1 fewer than the position, because 104 itself is number 1. So the 23rd needs 22 steps.")),
    beat("22 steps, and each step is 2. 22 times 2 is 44.", W("l3", "22 × 2 = 44")),
    beat("Start at 104 and go back 44. 104 minus 44 is 60. So the 23rd even number before 105 is 60.",
         answer("l4", "104 − 44 = 60"), ring("l4", "60")),
    beat("Test the idea on one we know. The 3rd is 2 steps back from 104: 104 minus 2 times 2 is 100. And 100 is third in our list.",
         W("l5", "104 − 2 × 2 = 100"), mark("l2", "100")),
    beat("So: find the first one, take 1 fewer steps than the position, and step back."),
]

