    beat("Now 616. 24 times 24 is 576, and 25 times 25 is 625. 616 falls in the gap between them.",
         W("l5", "24 × 24 = 576"), W("l6", "25 × 25 = 625"), strike("l3", "616", "in a gap")),
    beat("That leaves 729. It ends in 9, so its root ends in 3 or 7. It lies between 400 and 900, which is 30 times 30, and it is nearer to 900. Which root shall we test?",
         W("l7", "30 × 30 = 900"),
         ask=choose("27", ["23", "29"],
                    "The root ends in 3 or 7, and 729 is closer to 900 than to 400. So we want the bigger one, 27.")),
    beat("27 times 27. 27 times 20 is 540, and 27 times 7 is 189. Together, 729. It works!",
         W("l8", "27 × 27 = 27 × 20 + 27 × 7"), W("l9", "27 × 27 = 540 + 189 = 729")),
    beat("So there could be 729 pencils: 27 boxes with 27 pencils in each.",
         answer("l10", "729 = 27 × 27"), ring("l10", "729")),
    beat("When the number in each group equals the number of groups, the total is always a square number."),
