def line(lo, hi, step, points, hop=None):
    spec = {"kind": "numberLine", "min": lo, "max": hi, "step": step, "tickLabels": "none",
            "points": [{"at": p, "label": str(p)} for p in points]}
    if hop:
        spec["hops"] = [{"from": hop[0], "to": hop[1], "label": "?"}]
    return spec


