# Which fraction is closest to 1/2?
LESSONS["G5A_FRACTIONS_003"] = LESSON(
    B("Which of these fractions is closest to one half: 5 over 11, 4 over 7, 7 over 15 or 9 over 20?",
      GIVEN("q", "Closest to 1/2?"), LB("o", "5/11,  4/7,  7/15,  9/20")),
    B("Here is a neat trick. Ask what the top would have to be to make exactly one half. Half of 11 is 5 and a half. So 5 over 11 is half an eleventh short.",
      UL("o", "5/11")),
    B("Half of one eleventh is 1 over 22. So 5 over 11 is 1 over 22 below one half.",
      W("l1", "1/2 − 5/11 = 1/22")),
    B("Now 4 over 7. Half of 7 is 3 and a half, so 4 is half a seventh too many. It is 1 over 14 above one half.",
      W("l2", "4/7 − 1/2 = 1/14")),
    B("Your turn. Half of 15 is 7 and a half. So how far is 7 over 15 from one half?",
      ask=CHOOSE(["1/15", "1/30", "1/7"], 1,
                 "7 is half a part short, and each part is one fifteenth. Half of one fifteenth is 1 over 30.")),
    B("1 over 30 below. And 9 over 20: half of 20 is 10, so it is one whole twentieth short.",
      W("l3", "1/2 − 7/15 = 1/30"), W("l4", "1/2 − 9/20 = 1/20")),
    B("The gaps are 1 over 22, 1 over 14, 1 over 30 and 1 over 20. All have 1 on top. Which gap is the smallest?",
      ask=CHOOSE(["1/14", "1/30", "1/20"], 1,
                 "When the tops are all 1, a bigger bottom means smaller pieces. 30 is the biggest bottom, so 1 over 30 is the smallest gap.")),
    B("1 over 30 is the smallest gap, so 7 over 15 is the closest to one half.",
      CIRC("o", "7/15"), *ANSLC("l5", "7/15 is closest to 1/2", "7/15")),
    B("The trap is 9 over 20: it misses by one whole part, while 7 over 15 misses by only half a part."),
    B("So to compare fractions near one half, find each gap from one half. The smallest gap wins: 7 over 15."),
)

# Who has the most pizza left?
