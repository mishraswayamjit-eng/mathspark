# Half and ₹10 more, twice, leaves ₹20.
LESSONS["G5A_FRACTIONS_001"] = LESSON(
    B("Arjun spent half his money and 10 rupees more at the first stall. At the second he spent half of what was left and 10 rupees more. Then he had 20 rupees. How much did he take to the mela?",
      GIVEN("q", "half and ₹10 more, twice. Left: ₹20")),
    B("We know the end of the story, not the start. So we work backwards, like rewinding a film. Which stall do we undo first?",
      ask=CHOOSE(["the first stall", "the second stall"], 1,
                 "Rewinding goes from the end. The last thing that happened was the second stall, so that is undone first.")),
    B("At the second stall he paid half, then 10 rupees more, and was left with 20. Undo the last step first: give back the 10 rupees. 20 plus 10 is 30.",
      W("l1", "₹20 + ₹10 = ₹30")),
    B("That 30 is what was left after he paid half. So 30 is the other half. What did he bring to the second stall?",
      ask=CHOOSE(["₹15", "₹60", "₹40"], 1,
                 "If 30 rupees is one half, the whole amount is two halves. So we double 30.")),
    B("30 times 2 is 60. He had 60 rupees after the first stall.",
      W("l2", "₹30 × 2 = ₹60")),
    B("Now undo the first stall the same way. Give back the 10 rupees: 60 plus 10 is 70. Then double: 70 times 2 is 140.",
      W("l3", "₹60 + ₹10 = ₹70"), *ANSC("l4", "₹70 × 2 = ₹140", "₹140")),
    B("Careful with the order. Going backwards we add the 10 first and double second. Doubling first gives a different amount."),
    B("Check forwards. Half of 140 is 70, and 10 more makes 80 spent, leaving 60. Half of 60 is 30, and 10 more makes 40 spent, leaving 20. It fits.",
      W("l5", "140 − 80 = 60"), W("l6", "60 − 40 = 20")),
    B("So when you know the end, work backwards and undo each step in reverse order. Arjun took 140 rupees."),
)

