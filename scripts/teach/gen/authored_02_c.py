# Primes between 50 and 100 that stay prime when reversed.
LESSONS["G5A_DIVISIBILITY_014"] = LESSON(
    B("How many prime numbers between 50 and 100 are still prime when their digits are reversed?",
      GIVEN("q", "Primes from 50 to 100: still prime reversed?")),
    B("First, a careful list of the primes between 50 and 100. There are ten of them.",
      LB("p1", "53, 59, 61, 67, 71"), LB("p2", "73, 79, 83, 89, 97")),
    B("Watch out for 91. It looks prime, but 7 times 13 is 91, so it is not on our list.",
      W("l1", "7 × 13 = 91")),
    B("Now we reverse each one. Here is a shortcut: the first digit becomes the last digit. Which first digits spoil it straight away?",
      ask=CHOOSE(["5, 6 and 8", "7 and 9", "none of them"], 0,
                 "A number ending in 5 is a multiple of 5. A number ending in 6 or 8 is even. So primes that start with 5, 6 or 8 turn into numbers that are not prime.")),
    B("53 and 59 turn into 35 and 95, multiples of 5. 61 and 67 turn into 16 and 76, and 83 and 89 into 38 and 98, all even. Six are out.",
      STRIKE("p1", "53", "35"), STRIKE("p1", "59", "95"), STRIKE("p1", "61", "16"),
      STRIKE("p1", "67", "76"), STRIKE("p2", "83", "38"), STRIKE("p2", "89", "98")),
    B("Four are left: 71, 73, 79 and 97. Their reverses are 17, 37, 97 and 79.",
      LB("r", "17, 37, 97, 79")),
    B("17 and 37 are prime. And 97 and 79 are both on our list already: they are each other's reverse!",
      CIRC("p1", "71"), CIRC("p2", "73"), CIRC("p2", "79"), CIRC("p2", "97")),
    B("So 4 primes stay prime when reversed.",
      *ANSLC("l2", "71, 73, 79, 97: that is 4 primes", "4 primes")),
    B("The traps: letting 91 onto the list, or forgetting that 97 counts as well as 79."),
    B("So list carefully, reverse, and use the last digit to throw out the easy ones first. The answer is 4."),
)

