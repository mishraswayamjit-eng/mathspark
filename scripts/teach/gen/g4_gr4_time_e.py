"""Time and calendar lessons, part E: Q_CH17_004 to Q_CH17_014."""
from g4_gr4_time_lib import beat, given, w, lab, ans, mark, box, ring, note, strike, fig, choose

T = "gr4_time"
L = {}

L["Q_CH17_004"] = [
    beat("The 1st of January 2024 was a Monday. What day was the 1st of January 2025?",
         given("q", "1 January 2024 = Monday. 1 January 2025 = ?"), fig(T, "Q_CH17_004")),
    beat("Between these two dates lies the whole of the year 2024. So first we ask: how many days does 2024 have?"),
    beat("Is 2024 a leap year?",
         ask=choose("yes, 24 = 4 × 6", ["no, it is ordinary"],
                    "A leap year divides exactly by 4. 24 is 4 times 6, so 2024 divides exactly by 4. It is a leap year.")),
    beat("2024 is a leap year. So it has 366 days, one more than an ordinary year.",
         lab("a", "2024 is a leap year: 366 days"), box("a", "366 days")),
    beat("52 weeks make 364 days. So 366 days is 52 weeks and 2 days more.",
         w("b", "52 × 7 = 364"), w("c", "366 − 364 = 2")),
    beat("After 52 full weeks it is Monday again. Then 2 more days: Tuesday, Wednesday.",
         lab("d", "Mon → Tue → Wed")),
    beat("The 1st of January 2025 was a Wednesday.",
         ans("e", "1 January 2025 = Wednesday", "Wednesday")),
    beat("An ordinary year moves a date on 1 day. A leap year moves it on 2. Forget the leap day and you would stop at Tuesday."),
]

L["Q_CH17_005"] = [
    beat("Republic Day in 1993 was on a Tuesday. On which day did it fall in 1997?",
         given("q", "Republic Day 1993 = Tuesday. Republic Day 1997 = ?"), fig(T, "Q_CH17_005")),
    beat("Republic Day is the 26th of January. From 1993 to 1997 is 4 years, so we take 4 steps.",
         lab("r", "Republic Day = 26 January"), lab("y", "1993 → 1994 → 1995 → 1996 → 1997")),
    beat("An ordinary step moves the day on by 1, because 365 days is 52 weeks and 1 day.",
         w("a", "52 × 7 + 1 = 365")),
    beat("So 1994 gives Wednesday, 1995 gives Thursday, and 1996 gives Friday.",
         lab("b", "1994 Wed     1995 Thu     1996 Fri"),
         note("y", "1994", "+ 1", "below"), note("y", "1995", "+ 1", "below"), note("y", "1996", "+ 1", "below")),
    beat("1996 is a leap year. Its 29th of February comes after Republic Day 1996 and before Republic Day 1997. So how far does the last step move the day?",
         lab("c", "29 February 1996 is in between"),
         ask=choose("2 days", ["1 day", "4 days"],
                    "The leap day is inside that last stretch, so it has one extra day. The day moves on by 2.")),
    beat("Friday plus 2 is Sunday. Saturday gets skipped.",
         note("y", "1997", "+ 2", "below")),
    beat("Republic Day 1997 was a Sunday.",
         ans("d", "Republic Day 1997 = Sunday", "Sunday")),
    beat("Check by adding the steps: 1 plus 1 plus 1 plus 2 is 5. And 5 days after Tuesday is Sunday.",
         w("e", "1 + 1 + 1 + 2 = 5")),
    beat("Step one year at a time. Move 1 day, or 2 days when a 29th of February lies in between."),
]

