L["Q_CH17_014"] = [
    beat("How many odd days are there in 400 years?",
         given("q", "Odd days in 400 years = ?")),
    beat("Odd days are the days left over when full weeks are taken out. An ordinary year is 52 weeks and 1 day, so it has 1 odd day. A leap year has 2.",
         w("a", "52 × 7 + 1 = 365"), lab("b", "Ordinary year: 1 odd day.  Leap year: 2 odd days")),
    beat("So we must know how many of the 400 years are leap years. Every 4th year would give 400 divided by 4, which is 100.",
         w("c", "400 ÷ 4 = 100")),
    beat("But years ending in two zeros are special. In 400 years there are 4 of them. How many of those 4 are really leap years?",
         ask=choose("only 1", ["all 4", "none"],
                    "A year ending in two zeros is a leap year only if it divides by 400. Only 1 of the 4 does. The other 3 are ordinary.")),
    beat("So 3 of our 100 are not leap years after all. 100 minus 3 is 97 leap years. And 400 minus 97 is 303 ordinary years.",
         w("d", "100 − 3 = 97"), w("e", "400 − 97 = 303")),
    beat("Count the odd days. The ordinary years give 303. The leap years give 97 times 2, which is 194. Together that is 497.",
         w("f", "97 × 2 = 194"), w("g", "303 + 194 = 497")),
    beat("Now take out the full weeks. 7 times 71 is 497, exactly. Nothing is left over!",
         w("h", "7 × 71 = 497")),
    beat("So there are 0 odd days in 400 years.",
         ans("i", "0 odd days")),
    beat("That is why the calendar repeats itself every 400 years. Count the odd days, then take out the sevens."),
]
