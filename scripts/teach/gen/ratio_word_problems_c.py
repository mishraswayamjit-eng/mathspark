# In how many ways can 28 be written as a sum of two odd numbers?
LESSONS["EXT_G5_WS_B2_007"] = lesson(
    beat("In how many ways can 28 be written as a sum of two odd numbers?",
         G("q", "28 = odd number + odd number. How many ways?")),
    beat("Notice what it wants. Not one sum, but a count: how many different pairs of odd numbers add up to 28.",
         U("q", "How many ways")),
    beat("The secret of counting is to go in order. Start with the smallest odd number, 1. 1 plus what makes 28? 27, and 27 is odd. That is our first pair.",
         W("p1", "1 + 27 = 28")),
    beat("Next odd number, 3. 3 plus 25. Then 5 plus 23. See the pattern? One side goes up by 2, and the other comes down by 2.",
         W("p2", "3 + 25 = 28"), W("p3", "5 + 23 = 28")),
    beat("Keep going the same way. 7 plus 21. 9 plus 19. 11 plus 17. 13 plus 15.",
         W("p4", "7 + 21 = 28"), W("p5", "9 + 19 = 28"), W("p6", "11 + 17 = 28"), W("p7", "13 + 15 = 28")),
    beat("The next one would be 15 plus 13. Should we count it?",
         ask=ask(["yes, it is a new pair", "no, it is 13 + 15 again", "yes, and go on up to 27 + 1"], 1,
                 "15 plus 13 uses the same two numbers as 13 plus 15, only swapped round. It is the same pair, so we stop here.")),
    beat("So we stop, and count the lines on the board. 7 pairs, so 7 ways.",
         A("ans", "7 ways"), C("ans", "7 ways")),
    beat("A quick check. Our first numbers were 1, 3, 5, 7, 9, 11 and 13: every odd number below 14, which is half of 28. That is 7 numbers.",
         W("c1", "28 ÷ 2 = 14")),
    beat("Careful: 14 is a tempting answer. But pairs like 2 plus 26 use even numbers, so they do not count.",
         W("c2", "2 + 26 = 28"), X("c2", "2 + 26", "even + even")),
    beat("So to count ways, list them in order, smallest first, and stop when the pairs begin to repeat. That gave us our 7."),
)

