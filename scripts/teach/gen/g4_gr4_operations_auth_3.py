    B("A sum with a bracket at the end. Brackets go first, so we begin inside it.",
      GIVEN("q", "9 − 3 × 2 + (2 × 4 − 15 ÷ 3)")),
    B("Inside the bracket: 2 times 4 minus 15 divided by 3. Which jobs go first in there?",
      M("q", "(2 × 4 − 15 ÷ 3)", "box"),
      ask=choose(["2 × 4 and 15 ÷ 3", "4 − 15"], 0,
                 "Even inside a bracket, times and divide go before minus. So 2 times 4, and 15 divided by 3, go first.")),
    B("2 times 4 is 8. And 15 divided by 3 is 5.", W("a1", "2 × 4 = 8"), W("a2", "15 ÷ 3 = 5")),
    B("Finish the bracket. 8 take away 5 is 3. So the bracket is worth 3.", W("a3", "8 − 5 = 3"), W("l2", "9 − 3 × 2 + 3")),
    B("Now outside the bracket: 9 minus 3 times 2 plus 3. Careful, this is the trap. What goes first?",
      ask=choose(["3 × 2", "9 − 3"], 0, "Times goes before minus, even though the minus is written first. So 3 times 2 comes first.")),
    B("3 times 2 is 6. Now the sum is 9 minus 6 plus 3.", M("l2", "3 × 2", "box"), W("l3", "9 − 6 + 3")),
    B("Left to right. 9 take away 6 is 3. Then 3 plus 3 is 6.", W("l4", "9 − 6 = 3"), *ANSR("ans", "3 + 3 = 6", "6")),
    B("One more trap. The sign in front of the bracket is a plus. So the bracket's 3 is added at the end, not taken away."),
    B("So: bracket first, then times and divide, then plus and minus from left to right."),
