# PQR + PQR + PQR = QQQ: P + Q + R.
LESSONS[P + "OPERATIONS1_008"] = LESSON(
    B("Each letter stands for a digit, and different letters are different digits. P Q R, added three times, makes Q Q Q. We want P plus Q plus R.",
      GIVEN("q", "PQR + PQR + PQR = QQQ"), GIVEN("q2", "P + Q + R = ?")),
    B("The total, Q Q Q, has three equal digits. There are only a few numbers like that, so we can test them one by one.",
      LB("l0", "QQQ could be 111, 222, 333, ... 999")),
    B("If three lots of P Q R make Q Q Q, how do we get P Q R from Q Q Q?",
      ask=CHOOSE(["divide by 3", "multiply by 3", "subtract 3"], 0,
                 "Three equal numbers add up to Q Q Q. So each one is a third of it, and to find a third we divide by 3.")),
    B("Try 111: divided by 3 it gives 37, which has only 2 digits. 222 gives 74. 333 gives 111, whose digits are all the same. None of these fit.",
      W("l1", "111 ÷ 3 = 37"), W("l2", "222 ÷ 3 = 74"), W("l3", "333 ÷ 3 = 111")),
    B("Now 444. Divided by 3, it gives 148.",
      W("l4", "444 ÷ 3 = 148")),
    B("Here is the test that matters. Which digit of 148 has to match the Q of 444?",
      ask=CHOOSE(["the first digit, 1", "the middle digit, 4", "the last digit, 8"], 1,
                 "In P Q R the letter Q sits in the middle. So the middle digit of our number has to be the same as the repeated digit.")),
    B("The middle digit of 148 is 4, and Q is 4. It fits! And 1, 4 and 8 are all different.",
      UL("l4", "148")),
    B("The others do not fit. 555 gives 185, with 8 in the middle, not 5. 777 gives 259, 888 gives 296, and the rest repeat a digit.",
      W("l5", "555 ÷ 3 = 185"), W("l6", "777 ÷ 3 = 259"), W("l7", "888 ÷ 3 = 296")),
    B("So P is 1, Q is 4 and R is 8. 1 plus 4 plus 8 is 13.",
      *ANSC("l8", "1 + 4 + 8 = 13", 13)),
    B("Check: 148 plus 148 plus 148 is 444. Three equal digits, and the middle digit matches.",
      W("l9", "148 + 148 + 148 = 444")),
    B("So in a letter puzzle, look for the clue that leaves only a few choices, then test each one against every rule."),
)

