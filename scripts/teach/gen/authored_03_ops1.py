# 450 stickers altogether; if Riya gives 30 they are equal: Riya now?
LESSONS[P + "OPERATIONS1_001"] = LESSON(
    B("Riya and Kabir have 450 stickers altogether. If Riya gives 30 of hers to Kabir, they will have the same number. How many does Riya have now?",
      GIVEN("q", "Riya + Kabir: 450. Riya gives 30, then they are equal.")),
    B("Start at the moment after the gift, when they are equal. A gift only moves stickers from one hand to another, so the total is still 450."),
    B("After the gift they are equal, with 450 between them. How many does each child have then?",
      ask=CHOOSE(["450 ÷ 2", "450 − 30", "450 + 30"], 0,
                 "Two equal amounts that make 450 together: each one is half of 450.")),
    B("450 divided by 2 is 225. After the gift, each child has 225 stickers.",
      W("l1", "450 ÷ 2 = 225"), NOTE("l1", "225", "each, after the gift")),
    B("But the question asks what Riya has now, before she gives anything away. How does that compare with 225?",
      ask=CHOOSE(["30 more than 225", "30 less than 225", "exactly 225"], 0,
                 "Riya is the one who gives stickers away. She comes down to 225 only after losing 30, so right now she has 30 more.")),
    B("So we put her 30 stickers back in her hand. 225 plus 30 is 255. Riya has 255 stickers now.",
      *ANSC("l2", "225 + 30 = 255", 255)),
    B("The tempting slip is to stop at 225. That is what she will have after the gift, not what she has now."),
    B("Check. Kabir has 450 minus 255, which is 195. Give him 30 and he has 225. Riya drops from 255 to 225. Equal!",
      W("l3", "450 − 255 = 195"), W("l4", "195 + 30 = 225")),
    B("So when a gift makes two people equal: halve the total, then undo the gift for the person the question asks about."),
)

# Should subtract 386; copied it as 368 and added; got 2,154.
LESSONS[P + "OPERATIONS1_002"] = LESSON(
    B("Arjun had to subtract 386 from a number. By mistake he copied 386 as 368, and he added it instead of subtracting. He got 2154. What is the right answer?",
      GIVEN("q", "Asked: number − 386. Did: number + 368 = 2,154")),
    B("Arjun made two slips. He copied the number with two digits swapped, and he added when he should have subtracted.",
      UL("q", "386"), UL("q", "+ 368")),
    B("We do not know his starting number yet. But we know exactly what he did to it, so we can undo it."),
    B("He added 368 and reached 2154. How do we get back to his starting number?",
      ask=CHOOSE(["2,154 − 368", "2,154 − 386", "2,154 + 368"], 0,
                 "Undo exactly what he really did. He added 368, not 386, so we take 368 away from 2154.")),
    B("2154 minus 368 is 1786. That is the number Arjun started with.",
      W("l1", "2,154 − 368 = 1,786"), NOTE("l1", "1,786", "starting number")),
    B("Is 1786 our answer, or is there more to do?",
      ask=CHOOSE(["1,786 is the answer", "now subtract 386", "now subtract 368 again"], 1,
                 "1786 is only the number he began with. The job he was given was to subtract 386 from it, so we still have to do that.")),
    B("Now we do what he was asked, with the right number. 1786 minus 386 is 1400. The right answer is 1400.",
      *ANSC("l2", "1,786 − 386 = 1,400", "1,400")),
    B("Check by doing it Arjun's way. 1786 plus 368 is 2154, exactly what he got.",
      W("l3", "1,786 + 368 = 2,154")),
    B("So when someone has done a different sum from the one they were given: first undo what they really did, then do what they were asked."),
)

# Digits 1 to 6, two 3-digit numbers: smallest difference.
LESSONS[P + "OPERATIONS1_003"] = LESSON(
    B("The digits 1, 2, 3, 4, 5 and 6 are each used once to make two 3 digit numbers. What is the smallest possible difference between them?",
      GIVEN("q", "Digits 1, 2, 3, 4, 5, 6 make two 3-digit numbers."), GIVEN("q2", "Smallest difference?")),
    B("For a small difference, the two numbers must be as close together as we can get them. The hundreds digits matter most."),
    B("Which hundreds digits keep the two numbers close?",
      ask=CHOOSE(["far apart, like 6 and 1", "neighbours, like 4 and 3", "it makes no difference"], 1,
                 "Hundreds are worth the most. If the hundreds digits are far apart, the numbers are hundreds apart. Neighbours keep them close.")),
    B("Let's take 4 and 3 as the hundreds digits. The digits left over are 1, 2, 5 and 6.",
      LB("l1", "4 _ _ and 3 _ _    left: 1, 2, 5, 6")),
    B("Here is the insight. The bigger number, the one starting with 4, should be as small as it can be. The smaller number should be as large as it can be. They lean towards each other."),
    B("So what should the number starting with 4 be?",
      ask=CHOOSE(["412", "421", "465"], 0,
                 "We want the number starting with 4 to be as small as possible. So it takes the two smallest digits left, 1 and 2, with the smaller one first.")),
    B("The bigger number is 412. The other number gets 5 and 6. To be as large as possible it is 365, not 356.",
      LB("l2", "412 and 365   (365 is more than 356)")),
    B("412 minus 365 is 47.",
      *ANSC("l3", "412 − 365 = 47", 47)),
    B("Could other neighbours do better? With 3 and 2 the best is 314 minus 265, and with 5 and 4 it is 512 minus 463. Both give 49. So 47 is the smallest.",
      W("l4", "314 − 265 = 49"), W("l5", "512 − 463 = 49")),
    B("So for the smallest difference: choose neighbouring digits in front, then make the bigger number small and the smaller number big."),
)

# Facing pages add up to 437; turn 6 more leaves: right-hand page.
LESSONS[P + "OPERATIONS1_004"] = LESSON(
    B("A book lies open, and the two facing page numbers add up to 437. Kabir turns over 6 more leaves. What is the number on the right-hand page now?",
      GIVEN("q", "Facing pages add up to 437. Turn 6 more leaves.")),
    B("Facing pages carry numbers that follow one another, like 8 and 9. So we want two neighbours that add up to 437."),
    B("Half of 437 is 218 and a half. So the two pages sit just below and just above that: 218 and 219.",
      W("l1", "218 + 219 = 437")),
    B("The bigger one, 219, is on the right-hand page.",
      CIRC("l1", "219"), NOTE("l1", "219", "right-hand page")),
    B("Now Kabir turns 1 leaf. By how much do the page numbers go up?",
      ask=CHOOSE(["by 1", "by 2", "by 6"], 1,
                 "A leaf is one piece of paper, with a page on its front and a page on its back. Turning it takes you past both pages.")),
    B("Each leaf carries 2 pages. So 6 leaves move the numbers on by 6 times 2, which is 12. Adding only 6 is the trap here.",
      W("l2", "6 × 2 = 12")),
    B("219 plus 12 is 231. The right-hand page is now page 231.",
      *ANSC("l3", "219 + 12 = 231", 231)),
    B("Check. The left-hand page is now 218 plus 12, which is 230. And 230 and 231 are neighbours, with the bigger one on the right.",
      W("l4", "218 + 12 = 230")),
    B("So with books: facing pages are neighbours, and every leaf you turn moves the numbers on by 2."),
)

# A + B = 560, B + C = 640, A + C = 600: Bina?
LESSONS[P + "OPERATIONS1_005"] = LESSON(
    B("Asha and Bina have 560 rupees together. Bina and Chetan have 640. Asha and Chetan have 600. How much does Bina have?",
      GIVEN("q", "Asha + Bina = 560, Bina + Chetan = 640,"), GIVEN("q2", "Asha + Chetan = 600. Bina = ?")),
    B("Nobody's money is given alone, only in pairs. The trick is to add all three pairs together. 560 plus 640 plus 600 is 1800.",
      W("l1", "560 + 640 + 600 = 1800")),
    B("In that 1800, how many times has each child's money been counted?",
      ask=CHOOSE(["once", "twice", "three times"], 1,
                 "Look at Asha. She is in the first pair and in the third pair. In the same way, every child is in exactly 2 of the pairs.")),
    B("Each child is counted twice, so 1800 is double the real total. Halve it: the three children have 900 rupees together.",
      W("l2", "1800 ÷ 2 = 900"), NOTE("l2", "900", "all three together")),
    B("All three have 900. Which pair do we take away to leave only Bina?",
      ask=CHOOSE(["Asha and Bina, 560", "Bina and Chetan, 640", "Asha and Chetan, 600"], 2,
                 "To leave Bina alone, remove the two children who are not Bina. That is Asha and Chetan, and together they have 600.")),
    B("900 minus 600 is 300. Bina has 300 rupees.",
      UL("q2", "Asha + Chetan = 600"), *ANSC("l3", "900 − 600 = 300", 300)),
    B("The trap is to skip the halving and take 600 away from 1800. That number counts everybody twice."),
    B("Check. Asha has 560 minus 300, which is 260. Chetan has 640 minus 300, which is 340. And 260 plus 340 is 600, just as the question says.",
      W("l4", "560 − 300 = 260"), W("l5", "640 − 300 = 340"), W("l6", "260 + 340 = 600")),
    B("So when you are given every pair: add the pairs, halve to get everyone together, then take away the pair you do not want."),
)

