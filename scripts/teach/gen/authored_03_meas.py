# 3 mangoes + 2 guavas = 1150 g, 2 mangoes + 3 guavas = 1050 g: one mango?
LESSONS[P + "MEASUREMENT_012"] = LESSON(
    B("3 mangoes and 2 guavas weigh 1 kilogram 150 grams. 2 mangoes and 3 guavas weigh 1 kilogram 50 grams. We want the weight of one mango.",
      GIVEN("q", "3 mangoes + 2 guavas: 1 kg 150 g"), GIVEN("q2", "2 mangoes + 3 guavas: 1 kg 50 g")),
    B("First, grams everywhere. 1 kilogram is 1000 grams, so the two weighings are 1150 grams and 1050 grams.",
      LB("l1", "1 kg = 1000 g, so 1150 g and 1050 g")),
    B("The tempting move is to share 1150 grams equally among the 5 fruits. But a mango and a guava do not weigh the same, so equal sharing will not do."),
    B("Here is the clever idea: put the two weighings together. How many mangoes and how many guavas is that?",
      ask=CHOOSE(["5 mangoes and 5 guavas", "5 mangoes and 4 guavas", "6 mangoes and 6 guavas"], 0,
                 "Count each fruit across both weighings. 3 mangoes and 2 mangoes make 5 mangoes. 2 guavas and 3 guavas make 5 guavas.")),
    B("Together they weigh 1150 plus 1050, which is 2200 grams. That is 5 pairs of one mango and one guava, so one pair weighs 2200 divided by 5, which is 440 grams.",
      W("l2", "1150 + 1050 = 2200"), W("l3", "2200 ÷ 5 = 440"), NOTE("l3", "440", "1 mango + 1 guava")),
    B("Now compare the weighings. The first has a mango where the second has a guava, and it is 100 grams heavier. So a mango weighs 100 grams more than a guava.",
      W("l4", "1150 − 1050 = 100")),
    B("A mango and a guava weigh 440 grams, and the mango is 100 grams heavier. So what do 2 mangoes weigh?",
      ask=CHOOSE(["440 + 100 = 540 grams", "440 − 100 = 340 grams", "440 × 2 = 880 grams"], 0,
                 "Swap the guava in the pair for a second mango. A mango is 100 grams heavier than a guava, so the pair gets 100 grams heavier.")),
    B("2 mangoes weigh 540 grams. Halve it: one mango weighs 270 grams.",
      W("l5", "440 + 100 = 540"), *ANSC("l6", "540 ÷ 2 = 270", 270)),
    B("Check. A guava is 100 grams lighter, so it is 170 grams. Then 3 mangoes and 2 guavas come to 1150 grams, exactly the first weighing.",
      W("l7", "270 − 100 = 170"), W("l8", "3 × 270 + 2 × 170 = 1150")),
    B("So with two mixed weighings: add them to find one of each together, compare them to find the difference, and then split."),
)

# Candle 24 cm, 3 mm every 5 min, lit 10:50 a.m.: when is it 6 cm tall?
LESSONS[P + "MEASUREMENT_013"] = LESSON(
    B("A candle 24 centimetres tall burns down 3 millimetres every 5 minutes. It is lit at 10:50 in the morning. When will it be exactly 6 centimetres tall?",
      GIVEN("q", "24 cm candle burns 3 mm every 5 min, lit 10:50 a.m."), GIVEN("q2", "When is it exactly 6 cm tall?")),
    B("Read the 6 centimetres carefully. It is the part still standing. So how much of the candle has to burn away?",
      UL("q2", "6 cm tall"),
      ask=CHOOSE(["6 centimetres", "18 centimetres", "24 centimetres"], 1,
                 "The 6 centimetres is the part left standing, not the part that burns. The candle starts at 24, so take 6 away from 24.")),
    B("24 minus 6 is 18, so 18 centimetres must burn away. That is the trap in this question: the 6 is what stays, not what goes.",
      W("l1", "24 − 6 = 18")),
    B("The candle burns in millimetres, so we need the same unit. 1 centimetre is 10 millimetres, so 18 centimetres is 180 millimetres.",
      W("l2", "18 × 10 = 180"), NOTE("l2", "180", "millimetres")),
    B("It burns 3 millimetres at a time. How do we find how many lots of 3 millimetres are in 180?",
      ask=CHOOSE(["180 ÷ 3", "180 × 3", "180 − 3"], 0,
                 "We are asking how many threes fit into 180. Fitting equal lots into a number is a division.")),
    B("180 divided by 3 is 60 lots. Each lot takes 5 minutes, so the time is 60 times 5, which is 300 minutes.",
      W("l3", "180 ÷ 3 = 60"), W("l4", "60 × 5 = 300")),
    B("Notice it is not one minute for each millimetre. Now turn the minutes into hours: 300 divided by 60 is 5 hours.",
      W("l5", "300 ÷ 60 = 5")),
    B("5 hours after 10:50 in the morning. 2 hours take us to 12:50, and 3 more hours take us to 3:50 in the afternoon.",
      LB("l6", "10:50 a.m. + 2 hours = 12:50 p.m."), *ANSL("l7", "12:50 p.m. + 3 hours = 3:50 p.m.", "3:50 p.m.")),
    B("Check: 60 lots of 3 millimetres is 180 millimetres, which is 18 centimetres. And 24 minus 18 leaves 6 centimetres standing.",
      W("l8", "60 × 3 = 180")),
    B("So: find what must burn, match the units, count the lots, and turn the minutes into hours."),
)

# Steps of 60 cm and 90 cm over 36 m: shared heel marks, counting the start.
LESSONS[P + "MEASUREMENT_014"] = LESSON(
    B("Asha's steps are 60 centimetres long and her father's are 90 centimetres. They start on the same line and walk 36 metres. Counting the start, at how many places do their heel marks land on the same spot?",
      GIVEN("q", "Steps: Asha 60 cm, father 90 cm. They walk 36 m.")),
    B("Asha's heel lands at 60, 120, 180 and so on. Her father's lands at 90, 180, 270 and so on.",
      LB("a", "Asha: 60, 120, 180, 240 ..."), LB("f", "Father: 90, 180, 270 ...")),
    B("After the start, where do both heels first land on the same spot?",
      ask=CHOOSE(["at 150 cm, which is 60 + 90", "at 180 cm", "at 5400 cm, which is 60 × 90"], 1,
                 "Look for the first number that is in both lists. 180 is 3 of Asha's steps and 2 of her father's, so both heels land there.")),
    B("So the marks meet every 180 centimetres. Adding 60 and 90 is the tempting move, but 150 is not in either list.",
      CIRC("a", "180"), CIRC("f", "180")),
    B("The walk is 36 metres. 1 metre is 100 centimetres, so that is 3600 centimetres.",
      W("l1", "36 × 100 = 3600")),
    B("How many gaps of 180 centimetres fit in 3600? 3600 divided by 180 is 20.",
      W("l2", "3600 ÷ 180 = 20"), NOTE("l2", "20", "gaps")),
    B("20 gaps. So how many shared places are there, counting the starting line?",
      ask=CHOOSE(["20", "21", "19"], 1,
                 "Think of a fence. 20 gaps need a post at the start, and a post at the end of every gap. That is one more post than gaps.")),
    B("There is a shared mark at the end of each of the 20 gaps, and one more at the starting line. 20 plus 1 is 21 places.",
      *ANSC("l3", "20 + 1 = 21", 21)),
    B("Check with a short walk. In the first 360 centimetres the shared marks are at 0, 180 and 360. That is 2 gaps and 3 places: one more than the gaps again.",
      LB("l4", "0, 180, 360: 2 gaps, 3 places")),
    B("So shared marks come at common multiples. Count the gaps, then add 1 for the start."),
)

# Half then 150 ml; half of the rest then 100 ml; 200 ml left: the start?
LESSONS[P + "MEASUREMENT_015"] = LESSON(
    B("Kiran drank half the juice and then 150 millilitres more. His sister drank half of what was left and then 100 millilitres more. Now 200 millilitres are left. How much was in the jug at the start?",
      GIVEN("q", "Half, then 150 ml. Half of the rest, then 100 ml."), GIVEN("q2", "Left: 200 ml. At the start?")),
    B("We know the end but not the start. So we walk the story backwards, undoing the latest thing first."),
    B("What was the very last thing that happened to the juice?",
      ask=CHOOSE(["the sister drank 100 ml more", "the sister drank half", "Kiran drank 150 ml more"], 0,
                 "Read the story right to its end. The last thing before the 200 millilitres is the sister drinking her extra 100 millilitres.")),
    B("So put her 100 millilitres back. 200 plus 100 is 300. The jug held 300 millilitres just before her last drink.",
      W("l1", "200 + 100 = 300")),
    B("That 300 is what stayed after she drank half. So she found double that: 300 times 2 is 600 millilitres.",
      W("l2", "300 × 2 = 600")),
    B("Now we undo Kiran. He drank half, and then 150 millilitres more. Which do we undo first?",
      ask=CHOOSE(["double the 600", "put back the 150 ml", "take away 150 ml"], 1,
                 "Going backwards, the latest thing comes first. Kiran's extra 150 millilitres came after his half, so it goes back before we double.")),
    B("600 plus 150 is 750. Doubling first is the classic slip here. The extra drink came later, so it goes back first.",
      W("l3", "600 + 150 = 750")),
    B("And 750 is the half that Kiran left. Double it: 750 times 2 is 1500 millilitres. 1000 millilitres make 1 litre, so that is 1 litre 500 millilitres.",
      W("l4", "750 × 2 = 1500"), *ANSL("l5", "1500 ml = 1000 ml + 500 ml = 1 litre 500 ml", "1 litre 500 ml")),
    B("Check forwards. Half of 1500 is 750, less 150 is 600. Half of 600 is 300, less 100 is 200. Exactly what is left in the jug.",
      W("l6", "1500 ÷ 2 − 150 = 600"), W("l7", "600 ÷ 2 − 100 = 200")),
    B("So when the end is known and the start is not: work backwards, undo the latest step first, and do the opposite each time. The jug held 1 litre 500 millilitres."),
)

# 6 seconds to strike 4 o'clock: how long for 10 o'clock?
LESSONS[P + "MEASUREMENT_016"] = LESSON(
    B("A clock takes 6 seconds to strike 4 o'clock, timed from the first strike to the last. The gaps between strikes are equal. How long does it take to strike 10 o'clock?",
      GIVEN("q", "4 o'clock: 6 seconds, first strike to last. 10 o'clock?")),
    B("Picture the 4 strikes in a row. How many gaps are there between them?",
      LB("d", "strike - strike - strike - strike"),
      ask=CHOOSE(["4 gaps", "3 gaps", "5 gaps"], 1,
                 "Hold up 4 fingers and count the spaces between them. There are only 3 spaces. The gaps are always one fewer than the strikes.")),
    B("4 strikes have 3 gaps. The timing starts on the first strike and stops on the last, so the 6 seconds are filled by those 3 gaps.",
      W("l1", "4 − 1 = 3"), NOTE("l1", "3", "gaps")),
    B("So one gap is 6 divided by 3, which is 2 seconds. Sharing the 6 seconds among the 4 strikes is the tempting move, but the time passes in the gaps.",
      W("l2", "6 ÷ 3 = 2"), NOTE("l2", "2", "seconds a gap")),
    B("Now 10 o'clock. The clock strikes 10 times. How many gaps is that?",
      ask=CHOOSE(["10 gaps", "9 gaps", "11 gaps"], 1,
                 "It is the same idea as before. The gaps sit between the strikes, so there is one fewer gap than strikes.")),
    B("10 strikes have 9 gaps between them.",
      W("l3", "10 − 1 = 9")),
    B("9 gaps of 2 seconds each: 9 times 2 is 18. The clock takes 18 seconds to strike 10 o'clock.",
      *ANSC("l4", "9 × 2 = 18", 18)),
    B("Check our gap on the first clock. 3 gaps of 2 seconds make 6 seconds. That matches the question.",
      W("l5", "3 × 2 = 6")),
    B("So with strikes, posts or trees in a row: count the gaps, not the things. There is always one fewer gap."),
)

