# ── The wall, the door and two windows: how many cans of paint ───────────────
LESSONS[P + "e3d6e974-3349-4999-8241-fec781fef1ec"] = lesson(
    B("Meera is painting a wall, but not the door and not the two windows. One can covers 10 square metres, and we want to know how many cans to buy.",
      GIVEN("q1", "Wall 15 m × 8 m, door 2 m × 3 m"),
      GIVEN("q2", "2 windows, each 1.5 m × 1.5 m; 1 can covers 10 sq m")),
    B("Start with the whole wall. 15 times 8 is 120 square metres.",
      WN("a", "15 × 8 = 120", "120", "whole wall")),
    B("Not all of that gets painted. Which parts do we take away from the 120?",
      ask=choose(["the door only", "the door and one window", "the door and both windows"], 2,
                 "Read it once more: a door, and two windows, are left unpainted. So all three pieces come off the wall.")),
    B("The door is 2 times 3, which is 6 square metres.",
      WN("b", "2 × 3 = 6", "6", "door")),
    B("One window is 1.5 times 1.5, which is 2.25. Careful, there are two of them, so that is 4.5 square metres.",
      W("c", "1.5 × 1.5 = 2.25"), WN("d", "2 × 2.25 = 4.5", "4.5", "both windows")),
    B("Now take them off. 120 minus 6 is 114, and 114 minus 4.5 is 109.5 square metres to paint.",
      W("e", "120 − 6 = 114"), W("f", "114 − 4.5 = 109.5"), M("f", "109.5", "box")),
    B("Each can covers 10 square metres, so we divide by 10. 109.5 divided by 10 is 10.95.",
      W("g", "109.5 ÷ 10 = 10.95")),
    B("But a shop sells whole cans only. So how many must Meera buy?",
      ask=choose(["10 cans", "11 cans", "10.95 cans"], 1,
                 "10 cans would run out just before the wall is finished. She cannot buy part of a can, so she needs one more whole can.")),
    B("We round up, to 11 cans. Look: 10 cans cover only 100 square metres, but 11 cans cover 110, which is enough.",
      W("h", "10 × 10 = 100"), W("i", "11 × 10 = 110"), ANSR("j", "Cans to buy = 11", "11", True)),
    B("So: the whole area, take away what is left out, divide by what one can covers. And when you are buying, always round up."),
)

