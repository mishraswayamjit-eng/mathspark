from g4_gr4_fractions_lib import B, CH, FIG, MARK, NOTE, W, bars, bm, lesson, nline

LESSONS = {}


def A(qid, beats, check=None):
    LESSONS[qid] = lesson(beats, "authored", check)


def circles(*items):
    spec = bars(*items)
    spec["shape"] = "circle"
    return spec


def bmt(labels, tones, brace):
    return bm(labels, 0, brace, tones)


